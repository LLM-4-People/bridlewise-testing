#!/usr/bin/env node
// Mechanical design-system guard for the assembled docs site.
//
// One shell (docs/_layouts/default.html, built by scripts/floor/site.mjs)
// loads style.css and floor.css on every Jekyll page. This check reads the built HTML and refuses a content class
// with no CSS rule, or a floor.css class that no page uses. The allowlists
// name the only intentional exceptions, each with a reason.

import { readdirSync, readFileSync, statSync } from "node:fs";
import { join, relative } from "node:path";
import { htmlWithout } from "../../shared/markup.ts";

/** The stylesheets the one shell loads on every page (after the generated token sheet). */
export const SHARED_CSS = ["assets/css/style.css", "assets/floor/floor.css"];
const FLOOR_CSS = "assets/floor/floor.css";
export const STANDALONE_ALLOWLIST = new Map([
  ["/policy-lab/", "Standalone interactive governance demo with its own HTML shell and policy-lab.css."],
  ["/run/", "Standalone interactive run-record demo with its own HTML shell and run-demo.css."],
]);
const STANDALONE_PAGES = [...STANDALONE_ALLOWLIST.keys()].map((prefix) => new RegExp(`^${prefix.replace(/[.*+?^${}()|[\]\\]/gu, "\\$&")}`, "u"));

// Generated by Rouge inside pre/code; the token spans inherit the code colour.
const SYNTAX_CLASSES = new Set([
  "highlighter-rouge",
  "language-bash",
  "language-css",
  "language-json",
  "language-jsonc",
  "language-plaintext",
  "language-text",
  "language-ts",
  "c", "c1", "cd", "cm", "cs", "err", "gd", "ge", "ges", "gh", "gi", "go",
  "gp", "gr", "gs", "gt", "gu", "il", "k", "kc", "kd", "kn", "kp", "kr", "kt",
  "m", "mb", "mf", "mh", "mi", "mo", "na", "nb", "nc", "nd", "ne", "nf", "ni",
  "nl", "nn", "no", "nt", "nv", "nx", "o", "ow", "p", "pi", "s", "s1", "s2",
  "sb", "sc", "sd", "se", "sh", "si", "sr", "ss", "sx", "vc", "vg", "vi", "vm",
  "w",
]);

// Classes deliberately absent from the static CSS, with the reason they are
// still legitimate.
export const MISSING_ALLOWLIST = new Map([
  ["highlighter-rouge", "Rouge wrapper; token spans inherit the code colour."],
  ["language-bash", "Rouge language class; no component rule is needed."],
  ["language-css", "Rouge language class; no component rule is needed."],
  ["language-json", "Rouge language class; no component rule is needed."],
  ["language-jsonc", "Rouge language class; no component rule is needed."],
  ["language-plaintext", "Rouge language class; no component rule is needed."],
  ["language-text", "Rouge language class; no component rule is needed."],
  ["language-ts", "Rouge language class; no component rule is needed."],
]);

// floor.css has a few hooks that are constructed or toggled at runtime rather
// than emitted in Markdown. Each entry must say why no static page uses it.
export const UNUSED_ALLOWLIST = new Map([
  ["floor-pill", "Created by docs/assets/floor/floor.js for live status/atlas rows."],
  ["floor-empty", "Toggled by floor.js when a live region has no rows."],
]);

function walk(directory, extension, output = []) {
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) walk(path, extension, output);
    else if (entry.isFile() && entry.name.endsWith(extension)) output.push(path);
  }
  return output;
}

function pagePath(siteRoot, file) {
  return "/" + relative(siteRoot, file).split(/[\\/]/u).join("/");
}

function insideMain(html) {
  const start = html.indexOf('<main id="main"');
  if (start === -1) return "";
  const end = html.indexOf("</main>", start);
  if (end === -1) return "";
  return htmlWithout(
    html.slice(start, end).replace(/<nav class="breadcrumb"[\s\S]*?<\/nav>/u, ""),
    { elements: ["script", "style", "pre", "code"] },
  );
}

function tagsIn(markup) {
  const counts = new Map();
  for (const match of markup.matchAll(/<([a-zA-Z][\w-]*)\b/gu)) {
    const tag = match[1].toLowerCase();
    counts.set(tag, (counts.get(tag) ?? 0) + 1);
  }
  return counts;
}

function classesIn(markup) {
  const classes = new Set();
  for (const match of markup.matchAll(/class="([^"]*)"/gu)) {
    for (const name of match[1].trim().split(/\s+/u)) if (name) classes.add(name);
  }
  return classes;
}

function cssClasses(css) {
  const classes = new Set();
  const withoutComments = css.replace(/\/\*[\s\S]*?\*\//gu, "");
  for (const match of withoutComments.matchAll(/\.(-?[_a-zA-Z][\w-]*)/gu)) classes.add(match[1]);
  return classes;
}

/**
 * `exclude`: site-path prefixes judged elsewhere — a released docs snapshot
 * (`/v/<version>/`) was judged by its own build and never changes, so today's
 * stylesheets are not its yardstick.
 */
export function inventory(siteRoot, { exclude = [] } = {}) {
  const files = walk(siteRoot, ".html").filter((file) => !exclude.some((prefix) => pagePath(siteRoot, file).startsWith(prefix)));
  const pages = [];
  const tags = new Map();
  const classes = new Map();
  for (const file of files) {
    const path = pagePath(siteRoot, file);
    const html = readFileSync(file, "utf8");
    const main = insideMain(html);
    const foundTags = tagsIn(main);
    const foundClasses = classesIn(main);
    for (const [tag, count] of foundTags) tags.set(tag, (tags.get(tag) ?? 0) + count);
    for (const name of foundClasses) {
      if (!classes.has(name)) classes.set(name, []);
      classes.get(name).push(path);
    }
    pages.push({ path, classes: [...foundClasses].sort(), standalone: STANDALONE_PAGES.some((rx) => rx.test(path)) });
  }
  return { files, pages, tags, classes };
}

export function coverage(siteRoot, options = {}) {
  const inventoryResult = inventory(siteRoot, options);
  const sharedCss = SHARED_CSS.map((path) => readFileSync(join(siteRoot, path), "utf8")).join("\n");
  const floorCss = readFileSync(join(siteRoot, FLOOR_CSS), "utf8");
  const rules = cssClasses(sharedCss);
  const floorRules = cssClasses(floorCss);

  const missing = new Map();
  const used = new Set();
  for (const page of inventoryResult.pages) {
    if (page.standalone) continue;
    for (const name of page.classes) {
      used.add(name);
      if (!rules.has(name) && !SYNTAX_CLASSES.has(name) && !MISSING_ALLOWLIST.has(name)) {
        if (!missing.has(name)) missing.set(name, []);
        missing.get(name).push(page.path);
      }
    }
  }

  const unused = new Map();
  for (const name of floorRules) {
    if (used.has(name) || UNUSED_ALLOWLIST.has(name)) continue;
    unused.set(name, "floor.css declares it but no built page emits it.");
  }

  return {
    pages: inventoryResult.pages.length,
    jekyllPages: inventoryResult.pages.filter((page) => !page.standalone).length,
    standalonePages: inventoryResult.pages.filter((page) => page.standalone).map((page) => page.path),
    tags: inventoryResult.tags.size,
    classes: inventoryResult.classes.size,
    missing,
    unused,
  };
}

function printReport(result) {
  process.stdout.write(
    `design coverage: ${result.pages} pages (${result.jekyllPages} shared shell, ${result.standalonePages.length} standalone), ${result.tags} distinct elements, ${result.classes} distinct content classes\n`,
  );
  if (result.standalonePages.length > 0) {
    process.stdout.write(`  standalone pages excluded from the shared shell: ${result.standalonePages.join(", ")}\n`);
  }
  if (result.missing.size > 0) {
    process.stdout.write("  MISSING RULES\n");
    for (const [name, pages] of [...result.missing].sort()) {
      process.stdout.write(`  .${name}: ${pages.slice(0, 3).join(", ")}${pages.length > 3 ? ` (+${pages.length - 3})` : ""}\n`);
    }
  }
  if (result.unused.size > 0) {
    process.stdout.write("  UNUSED floor.css RULES\n");
    for (const [name] of [...result.unused].sort()) process.stdout.write(`  .${name}\n`);
  }
  if (result.missing.size === 0 && result.unused.size === 0) {
    process.stdout.write("  clean: every content class has a rule and every floor.css component rule is used\n");
  }
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const siteFlag = process.argv.indexOf("--site");
  const siteRoot = siteFlag === -1 ? join(process.cwd(), ".site/_site") : process.argv[siteFlag + 1];
  if (!statSync(siteRoot, { throwIfNoEntry: false })?.isDirectory()) {
    process.stderr.write(`design coverage: built site not found at ${siteRoot}\n`);
    process.exitCode = 2;
  } else {
    const result = coverage(siteRoot);
    if (process.argv.includes("--json")) process.stdout.write(JSON.stringify({
      pages: result.pages,
      jekyllPages: result.jekyllPages,
      standalonePages: result.standalonePages,
      tags: result.tags,
      classes: result.classes,
      missing: Object.fromEntries(result.missing),
      unused: Object.fromEntries(result.unused),
    }, null, 2) + "\n");
    else printReport(result);
    if (result.missing.size > 0 || result.unused.size > 0) process.exitCode = 1;
  }
}
