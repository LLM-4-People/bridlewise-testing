import assert from "node:assert/strict";
import { join, relative } from "node:path";
import test from "node:test";

import {
  CONFIG_FILE_BASENAME,
  PRODUCT_NAME,
  STATE_DIRECTORY_NAME,
} from "../../src/kernel/product-identity.ts";
import { readSourceView, sourceViewOf } from "../../scripts/verification/source-view.ts";
import { experimentExclusion, walk } from "../../scripts/verification/source-walk.ts";

const ROOT = process.cwd();
const SCAN_DIRS = ["src"];
const OWNER_PATH = join("src", "kernel", "product-identity.ts");

/**
 * The product identity (name, schema-namespace prefix, config-file basename,
 * state-directory name, crypto domain prefix) has ONE owner:
 * `src/kernel/product-identity.ts`. Every consumer derives the identity from
 * that owner (`schemaId` / `cryptoDomain` / `statePath` /
 * `CONFIG_FILE_BASENAME` / `STATE_DIRECTORY_NAME`), so a rename is a one-line
 * change at the owner instead of a tree-wide search that can miss a literal
 * and desynchronise two on-disk or wire formats that must agree.
 *
 * This guard denies, by default, any LOAD-BEARING product-identity literal in
 * product source (`src/**`) outside the owner. "Load-bearing" means a string
 * literal in a code position (a value, a comparison, a `z.literal`, a type
 * annotation) matching one of the identity shapes:
 *
 *   - a schema id:            `"<name>-<slug>/v<N>"`
 *   - a crypto domain:        `"<name>/<slug>/v<N>"` (optional NUL suffix)
 *   - a state path:           `".<name>"` / `".<name>/<...>"`
 *   - the config basename:    `"<name>.config.json"`
 *
 * A match inside a COMMENT is prose (a doc reference, an explanation) and is
 * NOT refused — only a string literal that could reach a parser, a
 * comparison, or a persisted/wire value counts.
 *
 * Declared exceptions (each is load-bearing but intentionally a literal):
 *   - the owner itself, which must spell the value to own it;
 *   - a file with a `Generated by … Do not edit` header, whose bytes are a
 *     projection re-derived from the owner on every regenerate;
 *   - `src/architecture-manifest.ts`, the auto-generated manifest projection;
 *   - the `testInventorySchema` literal in `src/kernel/root-policy.ts` and
 *     its paired `findRegex` in `src/workflow/hash-binding-registry.ts`: the
 *     hash-binding registry scans root-policy's SOURCE TEXT for that literal,
 *     so the pair moves together in the rename round, not independently.
 *
 * A new scattered identity literal reds this guard instead of silently
 * forking the identity.
 */

// Distinctive substring shared by every load-bearing identity literal. A file
// with no occurrence of the product name cannot contain one, so the scan
// short-circuits on the cheap substring before running the shape patterns.
const PRODUCT_SUBSTRING = PRODUCT_NAME;

// Escape the product name for use inside a RegExp, then build every identity
// shape from it. The shapes are DERIVED from the owner's PRODUCT_NAME, never
// restated as literals — so renaming the product at the owner retargets this
// guard automatically instead of leaving it scanning for the old name.
const REGEX_META = /[.*+?^${}()|[\]\\]/gu;
const P = PRODUCT_NAME.replace(REGEX_META, "\\$&");

const SCHEMA_ID_SHAPE = new RegExp(`"${P}-[a-z0-9-]+/v[0-9]+"`, "g");
const CRYPTO_DOMAIN_SHAPE = new RegExp(`"${P}/[a-z0-9/-]+/v[0-9]+(?:\\\\u0000)?"`, "g");
const STATE_PATH_SHAPE = new RegExp(`"\\.${P}(?:/[^"]*)?"`, "g");
const CONFIG_BASENAME_SHAPE = new RegExp(`"${P}\\.config\\.json"`, "g");
const SHAPES = [SCHEMA_ID_SHAPE, CRYPTO_DOMAIN_SHAPE, STATE_PATH_SHAPE, CONFIG_BASENAME_SHAPE];

const GENERATED_MARKER = /generated by[\s\S]*?do not edit/i;

function listTsFiles(dir: string, acc: string[] = []): string[] {
  for (const file of walk(dir, { exts: [".ts"], exclude: experimentExclusion(ROOT) })) {
    if (!file.endsWith(".test.ts")) acc.push(file);
  }
  return acc;
}

function productSourceFiles(): string[] {
  const files: string[] = [];
  for (const dir of SCAN_DIRS) listTsFiles(join(ROOT, dir), files);
  return files;
}

/** The declared per-file exceptions, keyed by repo-relative path. Each entry
 * is the set of literal strings permitted in that file. Empty set = the whole
 * file is exempt (the owner, generated projections). */
const OWNER_REL = OWNER_PATH.replaceAll("\\", "/");

/**
 * `isGenerated` reads the file's leading COMMENTS through the view's prose()
 * — a `Generated by … Do not edit` marker is a comment, so the prose view is
 * the correct input (never a raw byte read).
 */
function isGenerated(view: { prose(): readonly { text: string }[] }): boolean {
  const head = view.prose().slice(0, 6).map((c) => c.text).join("\n");
  return GENERATED_MARKER.test(head);
}

function permittedLiterals(relPath: string, generated: boolean): ReadonlySet<string> | "whole-file" {
  if (relPath === OWNER_REL) return "whole-file";
  if (generated) return "whole-file";
  if (relPath === join("src", "architecture-manifest.ts").replaceAll("\\", "/")) return "whole-file";
  if (relPath === join("src", "kernel", "root-policy.ts").replaceAll("\\", "/")) {
    // The text-scan-coupled inventory-schema literal (see header).
    return new Set([`"${PRODUCT_NAME}-test-inventory/v4"`]);
  }
  if (relPath === join("src", "workflow", "hash-binding-registry.ts").replaceAll("\\", "/")) {
    // The findRegex lookbehind that scans root-policy's source text.
    return new Set([`${PRODUCT_NAME}-test-inventory/v4`]);
  }
  return new Set();
}

interface Finding {
  file: string;
  literal: string;
  line: number;
}

interface IdentityView {
  codeWithStrings(): string;
  prose(): readonly { text: string }[];
  lineAt(i: number): number;
}

/**
 * Scan one file through the shared source-view owner. The view's
 * `codeWithStrings()` blanks COMMENTS but keeps quoted-string interiors — the
 * identity literals ARE quoted strings, so a match in that view is by
 * construction a code position, never prose. This is the §29-safe view: a
 * doc comment that QUOTES an identity literal is blanked and never flags.
 */
function scanView(relPath: string, view: IdentityView): Finding[] {
  const permitted = permittedLiterals(relPath, isGenerated(view));
  if (permitted === "whole-file") return [];
  const code = view.codeWithStrings();
  if (!code.includes(PRODUCT_SUBSTRING)) return [];
  const findings: Finding[] = [];
  for (const shape of SHAPES) {
    shape.lastIndex = 0;
    let m: RegExpExecArray | null;
    while ((m = shape.exec(code)) !== null) {
      const literalText = m[0];
      if (permitted.has(literalText)) continue;
      // the findRegex exception stores the bare (unquoted) token
      if (permitted.has(literalText.replace(/^"|"$/g, ""))) continue;
      findings.push({ file: relPath, literal: literalText, line: view.lineAt(m.index) });
    }
  }
  return findings;
}

function scanFile(absPath: string): Finding[] {
  const relPath = relative(ROOT, absPath).replaceAll("\\", "/");
  return scanView(relPath, readSourceView(absPath));
}

test("no product-identity literal is scattered outside the owner", () => {
  const files = productSourceFiles();
  assert.ok(files.length > 100, `expected a real src/ population, found ${files.length}`);
  const findings: Finding[] = [];
  for (const file of files) findings.push(...scanFile(file));
  assert.deepEqual(
    findings,
    [],
    "product-identity literals outside src/kernel/product-identity.ts (derive them from the owner via schemaId/cryptoDomain/statePath):\n" +
      findings.map((f) => `  ${f.file}:${f.line}: ${f.literal}`).join("\n"),
  );
});

test("the owner declares the identity values the guard reasons about", () => {
  const owner = readSourceView(join(ROOT, OWNER_PATH)).codeWithStrings();
  // The owner must spell the product name to own it; the guard's own
  // substring and shape patterns are derived from the owner, so a rename at
  // the owner retargets the guard automatically (no guard edit needed).
  assert.ok(owner.includes(`PRODUCT_NAME = "${PRODUCT_NAME}"`), "owner declares PRODUCT_NAME");
  assert.ok(owner.includes("export function schemaId"), "owner exports schemaId");
  assert.ok(owner.includes("export function cryptoDomain"), "owner exports cryptoDomain");
  assert.ok(owner.includes("export function statePath"), "owner exports statePath");
  assert.equal(CONFIG_FILE_BASENAME, `${PRODUCT_NAME}.config.json`);
  assert.equal(STATE_DIRECTORY_NAME, `.${PRODUCT_NAME}`);
});

test("DRIVEN: a planted identity literal in product source reds the scan", () => {
  // Plant a schema-id literal into an in-hand source body and drive it through
  // the same scanView the real scan uses (sourceViewOf — a fixture is not a
  // scan, so no temp file and no tracked-canary hazard). The witness proves
  // the detector was pointed at the planted bytes, not pointed at nothing.
  const witness = `${PRODUCT_NAME}-bogus-planted/v9`;
  const planted = `import { x } from "./somewhere.ts";\nexport const BOGUS = "${witness}";\n`;
  const found = scanView("src/kernel/planted-canary.ts", sourceViewOf(planted, "planted-canary.ts"));
  assert.ok(
    found.some((f) => f.literal === `"${witness}"`),
    `planted literal was not flagged (got ${JSON.stringify(found)})`,
  );
});

test("DRIVEN: a comment-quoting the identity is prose, not a finding", () => {
  // A doc comment that QUOTES an identity literal is blanked by the
  // codeWithStrings view, so it must produce no finding — the §29
  // stripped-view guarantee that prose references are not flagged.
  const prose = `// the schema id used to be spelled "${PRODUCT_NAME}-bogus-comment/v1" here\nexport const OK = 1;\n`;
  const found = scanView("src/kernel/comment-canary.ts", sourceViewOf(prose, "comment-canary.ts"));
  assert.deepEqual(found, [], "a comment-quoted identity literal must not be flagged");
});
