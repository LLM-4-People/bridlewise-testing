/**
 * THE GENERATOR OF THE VERB REGISTRY (`harness-verbs.ts`, #221).
 *
 * A verb is found by LOCATION and TYPE, never by its spelling: every module of
 * `src/workflow/commands/` IS a verb, and must export exactly one value,
 * `COMMAND`, of the one `HarnessCommand` shape (`{ verb, run }`), its verb
 * named after its file. The generator imports each module and judges the value
 * it exports; a module that does not export one — a renamed or missing export,
 * a second export, a verb named otherwise — is a typed refusal
 * (`command_registry_invalid`), so a verb can never vanish from the CLI while
 * every test stays green. The registry is one import and one entry per verb,
 * in verb order; it is wholly generated, so a merge conflict on it resolves to
 * either side and regenerates.
 *
 * It runs as a subprocess of `harness check` (the `command-registry` step) and
 * `harness regenerate` (which writes it): importing the verb modules is
 * asynchronous, and those arms answer synchronously.
 *
 * Usage: `node scripts/verification/command-registry.ts --check|--write`
 * Prints ONE JSON line: `{ allCurrent, status, changed, verbs }`.
 */
import { existsSync, readdirSync, readFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { atomicWriteFile } from "../../src/filesystem/atomic-write.ts";
import { HarnessError } from "../../src/kernel/errors.ts";
import { canonicalJson } from "../../src/kernel/integrity.ts";
import { bootstrapProcess, isEntryPoint } from "../../src/runtime/cli-debug.ts";

/** The folder of the verb modules, and the generated registry, engine-relative. */
export const COMMANDS_FOLDER = "src/workflow/commands";
export const COMMAND_REGISTRY_PATH = "src/workflow/harness-verbs.ts";
/** The one name a verb module exports. */
const COMMAND_EXPORT = "COMMAND";
const VERB = /^[a-z][a-z-]*$/u;

export type CommandRegistryReport = Readonly<{
  allCurrent: boolean;
  status: "current" | "stale" | "written";
  changed: readonly string[];
  verbs: readonly string[];
}>;

function refuse(message: string): never {
  throw new HarnessError(message, "command_registry_invalid");
}

/**
 * The verbs of the modules in `folder`, sorted: each module is imported and
 * must export exactly `COMMAND`, a `{ verb, run }` whose verb is its file's
 * name. Anything else is a refusal.
 */
export async function declaredVerbs(folder: string): Promise<readonly string[]> {
  const modules = readdirSync(folder).filter((name) => name.endsWith(".ts")).toSorted();
  if (modules.length === 0) refuse(`${COMMANDS_FOLDER} holds no verb module`);
  const verbs: string[] = [];
  for (const name of modules) {
    const exported = await import(pathToFileURL(join(folder, name)).href) as Readonly<Record<string, unknown>>;
    const names = Object.keys(exported);
    if (names.length !== 1 || names[0] !== COMMAND_EXPORT) {
      refuse(`${COMMANDS_FOLDER}/${name} must export exactly one value, ${COMMAND_EXPORT}: HarnessCommand; it exports ${names.length === 0 ? "nothing" : names.join(", ")}`);
    }
    const command = exported[COMMAND_EXPORT] as { verb?: unknown; run?: unknown } | null;
    if (typeof command !== "object" || command === null || typeof command.verb !== "string" || !VERB.test(command.verb) || typeof command.run !== "function") {
      refuse(`${COMMANDS_FOLDER}/${name} exports a ${COMMAND_EXPORT} that is not a HarnessCommand ({ verb, run })`);
    }
    if (`${command.verb}.ts` !== name) refuse(`${COMMANDS_FOLDER}/${name} declares the verb ${command.verb}: a verb lives in the module named after it`);
    verbs.push(command.verb);
  }
  return verbs;
}

/** The registry's text for `verbs`. */
export function commandRegistryText(verbs: readonly string[]): string {
  const binding = (verb: string): string => `${verb.replace(/-([a-z])/gu, (_, letter: string) => letter.toUpperCase())}Command`;
  return [
    "// GENERATED by `harness sync` from the verb modules of src/workflow/commands/ (scripts/verification/command-registry.ts); do not edit.",
    'import type { HarnessCommand } from "./harness-command.ts";',
    ...verbs.map((verb) => `import { COMMAND as ${binding(verb)} } from "./commands/${verb}.ts";`),
    "",
    "/** Every harness verb, in verb order. */",
    "export const HARNESS_COMMANDS: readonly HarnessCommand[] = [",
    ...verbs.map((verb) => `  ${binding(verb)},`),
    "];",
    "",
  ].join("\n");
}

/** Judges (and with `write`, rewrites) the registry of the engine at `engineRoot`. */
export async function syncCommandRegistry(engineRoot: string, write: boolean): Promise<CommandRegistryReport> {
  const verbs = await declaredVerbs(join(engineRoot, COMMANDS_FOLDER));
  const expected = commandRegistryText(verbs);
  const path = join(engineRoot, COMMAND_REGISTRY_PATH);
  const current = existsSync(path) ? readFileSync(path, "utf8") : undefined;
  if (current === expected) return Object.freeze({ allCurrent: true, status: "current", changed: [], verbs });
  if (write) {
    const result = atomicWriteFile(path, expected);
    if (!result.success) throw new HarnessError(`could not write ${COMMAND_REGISTRY_PATH}: ${result.reason ?? "atomic write failed"}`, "command_registry_write_failed");
  }
  return Object.freeze({ allCurrent: false, status: write ? "written" : "stale", changed: [COMMAND_REGISTRY_PATH], verbs });
}

if (isEntryPoint(import.meta.url)) {
  bootstrapProcess({ role: "cli" });
  const argv = process.argv.slice(2);
  if (argv.length !== 1 || !["--check", "--write"].includes(argv[0]!)) throw new Error("Usage: command-registry --check|--write");
  const engineRoot = resolve(fileURLToPath(new URL("../../", import.meta.url)));
  try {
    const report = await syncCommandRegistry(engineRoot, argv[0] === "--write");
    process.stdout.write(`${canonicalJson(report)}\n`);
    process.exitCode = report.allCurrent || report.status === "written" ? 0 : 1;
  } catch (error) {
    // The refusal is ONE typed line on stderr, the generator channel the harness reads.
    process.stderr.write(`${JSON.stringify({
      error: error instanceof HarnessError ? error.code : "command_registry_failed",
      message: error instanceof Error ? error.message : String(error),
    })}\n`);
    process.exitCode = 1;
  }
}
