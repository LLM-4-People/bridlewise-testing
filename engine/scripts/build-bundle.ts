/**
 * Build script for the self-protection production bundle. Bundles
 * `src/bundle-entry.ts` (which re-exports `runCli` from `src/cli.ts` +
 * `loadPinnedConfigSnapshot` from `src/config.ts`) + its entire import graph
 * (including `@babel/parser` and `zod`) into a single self-contained ESM file
 * `dist/bundle.js` so the Landlock allow-set does not need `node_modules` (the
 * bundle is the only harness file the restricted payload reads). The bundle
 * entry is separate from the package public API (`src/cli.ts`, which exports
 * only `runCli`) so the S1-B06-HOSTILE-REAL package-surface scenario and the
 * Landlock e2e probe each get exactly the exports they need. Also writes
 *   - `traceability/self-protection/guardian-spec-schema.json` (the published
 *     Draft 2020-12 projection of `GUARDIAN_SPEC_SCHEMA`).
 *
 * This is a BUILD-TIME script (dev/CI); it does NOT run under Landlock. The
 * runtime has zero new native deps — `esbuild` is a `devDependency` only.
 *
 * Usage: `node scripts/build-bundle.ts` (Node 24 strips types natively).
 *
 * Determinability: `sourcesContent: false` + esbuild's deterministic output
 * + no sourcemap, so the bundle's bytes are a pure function of the source
 * tree + esbuild version. No digest of it is committed (#221): a build
 * output's identity is the build's to report, never a value the tree holds,
 * and the bundle-staleness guard proves the bundle on disk is a fresh build.
 * `node src/cli.ts harness sync --with-bundle` builds it with the rest of the
 * generated values; this script is the lower-level build step.
 */

import { existsSync, mkdirSync, readFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

import { build } from "esbuild";

import { atomicWriteFile } from "../src/filesystem/atomic-write.ts";
import { sha256 } from "../src/kernel/integrity.ts";
import { buildGuardianSpecSchemaArtifact } from "./verification/slice-projections.ts";
import { bootstrapProcess, isEntryPoint } from "../src/runtime/cli-debug.ts";

const harnessRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const entryPath = join(harnessRoot, "src", "bundle-entry.ts");
const outDir = join(harnessRoot, "dist");
const bundlePath = join(outDir, "bundle.js");

type EsbuildPackage = Readonly<{ version: string; license: string }>;

function readEsbuildPackage(): EsbuildPackage {
  const pkgPath = join(harnessRoot, "node_modules", "esbuild", "package.json");
  const raw = JSON.parse(readFileSync(pkgPath, "utf8")) as Readonly<{ version?: unknown; license?: unknown }>;
  return {
    version: typeof raw.version === "string" ? raw.version : "unknown",
    license: typeof raw.license === "string" ? raw.license : "unknown",
  };
}

/**
 * Returns the esbuild options for the production bundle. Exported so the
 * bundle-staleness prevention test can rebuild the bundle in-memory
 * (write:false) and verify the hash matches the root-policy pin — without
 * duplicating the options (DRY).
 */
export function getBundleBuildOptions(): Parameters<typeof build>[0] {
  return {
    entryPoints: [entryPath],
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node24",
    outfile: bundlePath,
    sourcemap: false,
    sourcesContent: false,
    // A dependency is named by the path it is reached by, never its real path: a checkout whose node_modules is a
    // link (a worktree, the commit guard's staged tree) builds the same bytes as one that holds the folder, so the
    // bundle is a function of the tree and the lockfile, never of where the dependencies happen to sit (#221).
    preserveSymlinks: true,
    write: false,
    logLevel: "warning",
    external: ["onnxruntime-node", "sharp", "@xenova/transformers"],
    banner: {
      js: "// bridlewise production bundle — generated by scripts/build-bundle.ts; do not edit by hand. Landlock self-protection: allow-list this file (READ_FILE) in the guardian spec.",
    },
  };
}

type BuildSummary = Readonly<{
  bundlePath: string;
  bundleSha256: string;
  bundleBytes: number;
  specSchemaArtifactPath: string;
  specSchemaArtifactSha256: string;
  esbuildVersion: string;
  esbuildLicense: string;
  entryPath: string;
  format: string;
  platform: string;
  target: string;
  sourcemap: boolean;
}>;

function writeArtifactIfChanged(path: string, text: string, label: string): void {
  if (existsSync(path) && readFileSync(path, "utf8") === text) return;
  mkdirSync(dirname(path), { recursive: true });
  const write = atomicWriteFile(path, text);
  if (!write.success) {
    throw new Error(`Could not write ${label}: ${write.reason ?? "unknown"}`);
  }
}

/**
 * Publish the bundle: the built text, written when it differs, and its
 * digest (reported, never committed). Two fresh checkouts of one tree publish
 * the same bytes, whatever bundle (if any) was on disk before (FR-15).
 */
export function publishBundle(bundleText: string, destination: string): Readonly<{
  bundleSha256: string;
  bundleBytes: number;
}> {
  writeArtifactIfChanged(destination, bundleText, "bundle");
  // No `bundle.js.sha256` sidecar: nothing read it, and copy-back left it
  // stale beside a new bundle (wf1a-design L6).
  return { bundleSha256: sha256(bundleText), bundleBytes: Buffer.byteLength(bundleText) };
}

async function buildBundle(): Promise<BuildSummary> {
  const esbuildPkg = readEsbuildPackage();
  const result = await build(getBundleBuildOptions());
  const outputFiles = result.outputFiles ?? [];
  const bundleText = outputFiles[0]?.text;
  if (bundleText === undefined) {
    throw new Error("esbuild produced no output files");
  }
  const published = publishBundle(bundleText, bundlePath);
  const artifact = buildGuardianSpecSchemaArtifact();
  const artifactAbsPath = join(harnessRoot, artifact.path);
  writeArtifactIfChanged(artifactAbsPath, artifact.bytes, "guardian spec schema artifact");
  return {
    bundlePath,
    ...published,
    specSchemaArtifactPath: artifact.path,
    specSchemaArtifactSha256: artifact.sha256,
    esbuildVersion: esbuildPkg.version,
    esbuildLicense: esbuildPkg.license,
    entryPath,
    format: "esm",
    platform: "node",
    target: "node24",
    sourcemap: false,
  };
}

/**
 * THE BUNDLE'S FRESHNESS, with no committed digest (#221): a rebuild in memory
 * from the current source, compared byte for byte with `dist/bundle.js`. A
 * stale, tampered or absent bundle is `fresh: false`, naming which; nothing is
 * written. `harness check` runs this (`--check`), so a hand-edited bundle is
 * refused by the check that refuses every other drift.
 */
export async function bundleFreshness(onDisk: string = bundlePath): Promise<Readonly<{ fresh: boolean; status: "current" | "stale" | "absent"; path: string }>> {
  const result = await build(getBundleBuildOptions());
  const rebuilt = result.outputFiles?.[0]?.text;
  if (rebuilt === undefined) throw new Error("esbuild produced no output files");
  const status = !existsSync(onDisk) ? "absent" : readFileSync(onDisk, "utf8") === rebuilt ? "current" : "stale";
  return { fresh: status === "current", status, path: relative(harnessRoot, onDisk) };
}

if (isEntryPoint(import.meta.url)) {
  bootstrapProcess({ role: "cli" });
  const argv = process.argv.slice(2);
  if (argv.length > 1 || (argv.length === 1 && argv[0] !== "--check")) throw new Error("Usage: build-bundle [--check]");
  if (argv[0] === "--check") {
    const freshness = await bundleFreshness();
    process.stdout.write(`${JSON.stringify(freshness)}\n`);
    process.exit(freshness.fresh ? 0 : 1);
  }
  const summary = await buildBundle();
  process.stdout.write(`${JSON.stringify(summary, null, 2)}\n`);
  process.exit(0);
}
