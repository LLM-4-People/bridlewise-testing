/**
 * THE COMMUNITY HEALTH FILES AND FORMS, generated (github-only §10.3): every
 * file GitHub shows a contributor — CONTRIBUTING, CODE_OF_CONDUCT, SECURITY,
 * SUPPORT, GOVERNANCE, the pull-request template, the issue forms, the
 * chooser's `config.yml` and the Discussion forms — is written by
 * `harness sync` from its single sources and judged by `harness check`, never
 * edited by hand.
 *
 * The sources:
 *   - the prose: `docs/community/templates/<file>.tmpl`, with `{{slot}}` slots
 *     (not `.md`, so the link guards judge the rendered file, never a slot);
 *     every template is rendered, so one that names no output is drift;
 *   - the facts that fill the slots, each from its one owner: the role table,
 *     the intake registry and the features with their live or planned status
 *     (`sources.ts`), the repository identity and the supported Node range
 *     (`package.json`), the guardian's declared compiler
 *     (`engine/guardian/Makefile`).
 *
 * THE GENERATOR OWNS EVERY PLACE GITHUB READS THESE FILES FROM: a health
 * file's name (any case, any extension) at the root, in `.github/` or in
 * `docs/` other than the generated path, and any file in a template folder
 * (`ISSUE_TEMPLATE/`, `DISCUSSION_TEMPLATE/`, `PULL_REQUEST_TEMPLATE/`) the
 * generator did not write, is a SHADOW: GitHub may show it instead of, or
 * beside, the generated file. `harness check` names each; `harness sync`
 * deletes the generator's own stale outputs and refuses a hand-made one
 * (`community_shadow_file`), never deleting a person's file.
 *
 * A tree with no community surface at all (no sources and no health file
 * anywhere) is converged by absence; once any is present, the sources are
 * required, and a missing one is `community_source_invalid`.
 */
import { existsSync, lstatSync, mkdirSync, readFileSync, readdirSync, rmSync } from "node:fs";
import { dirname, join } from "node:path";

import { atomicWriteFile } from "../../filesystem/atomic-write.ts";
import { HarnessError, InputError } from "../../kernel/errors.ts";
import { emitYaml, type YamlValue } from "../../text/yaml-emit.ts";
import { escapeMarkdownTableCell } from "../../../../shared/markup.ts";
import { configuredRepositoryIdentity } from "../forge/repository-identity.ts";
import {
  COMMUNITY_DIRECTORY,
  CONFIRMATIONS_FIELD_ID,
  isLive,
  readFeatures,
  readIntake,
  readRoles,
  ROLES_PATH,
  type ClaimStatus,
  type CommunityFeature,
  type CommunityIntake,
  type CommunityRoles,
  type FormField,
} from "./sources.ts";

const TEMPLATES_DIRECTORY = `${COMMUNITY_DIRECTORY}/templates`;
const ISSUE_FORMS_DIRECTORY = ".github/ISSUE_TEMPLATE";
const DISCUSSION_FORMS_DIRECTORY = ".github/DISCUSSION_TEMPLATE";
const TEMPLATE_SUFFIX = ".tmpl";

/** The Markdown files rendered from a template of the same name, repository-relative. */
export const TEMPLATED_FILES = Object.freeze([
  "CONTRIBUTING.md",
  "CODE_OF_CONDUCT.md",
  "SECURITY.md",
  "SUPPORT.md",
  "GOVERNANCE.md",
  ".github/PULL_REQUEST_TEMPLATE.md",
] as const);

/** Where GitHub looks for a community health file, repository-relative (`""` is the root). */
const HEALTH_LOCATIONS = Object.freeze(["", ".github", "docs"] as const);
/** The health-file names GitHub reads (compared lower-cased, without extension); the template ones may also be folders. */
const HEALTH_NAMES = Object.freeze(["code_of_conduct", "contributing", "governance", "security", "support", "pull_request_template", "issue_template", "discussion_template"] as const);

export type CommunityFacts = Readonly<{
  roles: CommunityRoles;
  intake: CommunityIntake;
  features: readonly CommunityFeature[];
  /** `owner/name` of the GitHub repository (the one repository identity, `forge/repository-identity.ts`). */
  repository: string;
  nodeRange: string;
  compiler: string;
}>;

export type CommunityFilesReport = Readonly<{
  status: "current" | "regenerated" | "stale" | "absent";
  converged: boolean;
  changed: readonly string[];
}>;

const GENERATED_MARK = "GENERATED by `harness sync`";

function templateInvalid(path: string, why: string): never {
  throw new InputError(`${path}: ${why}`, "community_template_invalid", { path });
}

/** The facts the generated files carry, each read from its one owner. */
function readCommunityFacts(repositoryRoot: string): CommunityFacts {
  let manifest: { engines?: { node?: unknown } };
  try {
    manifest = JSON.parse(readFileSync(join(repositoryRoot, "package.json"), "utf8")) as typeof manifest;
  } catch (error) {
    templateInvalid("package.json", `unreadable as JSON (${(error as Error).message})`);
  }
  const repository = configuredRepositoryIdentity().fullName;
  const nodeRange = manifest.engines?.node;
  if (typeof nodeRange !== "string") templateInvalid("package.json", "engines.node is not declared");
  const makefile = "engine/guardian/Makefile";
  const compiler = /^CC\s*:=\s*(\S+)$/mu.exec(readFileSync(join(repositoryRoot, makefile), "utf8"))?.[1];
  if (compiler === undefined) templateInvalid(makefile, "declares no CC := … line");
  return Object.freeze({ roles: readRoles(repositoryRoot), intake: readIntake(repositoryRoot), features: readFeatures(repositoryRoot), repository, nodeRange, compiler });
}

const repositoryUrl = (facts: CommunityFacts): string => `https://github.com/${facts.repository}`;
const advisoryUrl = (facts: CommunityFacts): string => `${repositoryUrl(facts)}/security/advisories/new`;
const categoryUrl = (facts: CommunityFacts, slug: string): string => `${repositoryUrl(facts)}/discussions/new?category=${slug}`;

/** A Markdown table cell: escaped by the one markup owner (backslash and pipe), line breaks folded, so a source string never breaks the table. */
function cell(text: string): string {
  return escapeMarkdownTableCell(text).replace(/\s*\n\s*/gu, " ");
}

/** A planned claim's line: what it will be, and where it is tracked (its issue, under the repository identity). */
function plannedLine(facts: CommunityFacts, text: string, status: ClaimStatus): string {
  return `- ${text} Planned; tracked in ${"planned" in status ? `${repositoryUrl(facts)}/issues/${String(status.planned)}` : ""}.`;
}

/** Every slot a template may name, rendered from the facts. `feature:<id>` is the feature's sentence while live, and empty while planned. */
function communitySlots(facts: CommunityFacts): ReadonlyMap<string, string> {
  const { roles, intake, features } = facts;
  const titleOf = new Map(roles.roles.map((role) => [role.id, role.title]));
  const teamsLive = features.some((feature) => feature.id === "teams" && isLive(feature.status));
  const liveCategories = intake.discussionCategories.filter((category) => isLive(category.status));
  const planned = [
    ...features.filter((feature) => !isLive(feature.status)).map((feature) => plannedLine(facts, feature.text, feature.status)),
    ...intake.discussionCategories.filter((category) => !isLive(category.status)).map((category) => plannedLine(facts, `The ${category.name} Discussion category: ${category.use}.`, category.status)),
    ...intake.issueForms.filter((form) => !isLive(form.typeStatus)).map((form) => plannedLine(facts, `The ${form.type} issue type, set by the ${form.name} form.`, form.typeStatus)),
  ];
  const slots = new Map([
    ["repository", facts.repository],
    ["repositoryName", facts.repository.split("/")[1]!],
    ["repositoryUrl", repositoryUrl(facts)],
    ["advisoryUrl", advisoryUrl(facts)],
    ["nodeRange", facts.nodeRange],
    ["compiler", facts.compiler],
    [
      "roleTable",
      [
        "| Role | GitHub access | Approval counts as verification | Earned by |",
        "|---|---|---|---|",
        ...roles.roles.map((role) => `| ${cell(role.title)} | ${cell(role.access)}${teamsLive && role.team !== null ? `, team \`${role.team}\`` : ""} | ${role.verifies ? "yes, on pull requests they did not author" : "no"} | ${cell(role.earnedBy)} |`),
      ].join("\n"),
    ],
    ["members", roles.members.map((member) => `- [@${member.login}](https://github.com/${member.login}), ${titleOf.get(member.role)!}`).join("\n")],
    [
      "discussionCategories",
      [
        "| Category | Who posts | Use |",
        "|---|---|---|",
        ...liveCategories.map((category) => `| [${cell(category.name)}](${repositoryUrl(facts)}/discussions/categories/${category.slug}) | ${cell(category.postedBy)} | ${cell(category.use)} |`),
      ].join("\n"),
    ],
    ["issueForms", intake.issueForms.map((form) => `- [${form.name}](${repositoryUrl(facts)}/issues/new?template=${form.file}): ${form.description}`).join("\n")],
    ["planned", planned.length === 0 ? "Nothing is planned here at the moment." : planned.join("\n")],
    ...features.map((feature): [string, string] => [`feature:${feature.id}`, isLive(feature.status) ? feature.text : ""]),
  ]);
  // The conduct contact may name the facts' slots (the private reporting form's URL).
  slots.set("conductContact", fillTemplate(ROLES_PATH, roles.conduct.contact, slots));
  return slots;
}

const SLOT = /\{\{([A-Za-z]+(?::[a-z][a-z0-9-]*)?)\}\}/gu;

/** `template` with every slot filled; an unknown slot is `community_template_invalid`. Lines a planned feature empties leave no blank run. */
export function fillTemplate(path: string, template: string, slots: ReadonlyMap<string, string>): string {
  const filled = template.replace(SLOT, (_whole, name: string) => slots.get(name) ?? templateInvalid(path, `names the unknown slot {{${name}}} (known: ${[...slots.keys()].join(", ")})`));
  return filled.replace(/\n{3,}/gu, "\n\n");
}

function generatedNotice(sources: string): string {
  return `${GENERATED_MARK} from ${sources}. Edit the sources, never this file.`;
}

function formBody(fields: readonly FormField[]): YamlValue[] {
  return fields.map((field) => {
    const attributes: { [key: string]: YamlValue } = { label: field.label };
    if (field.description !== undefined) attributes.description = field.description;
    if (field.placeholder !== undefined) attributes.placeholder = field.placeholder;
    if (field.render !== undefined) attributes.render = field.render;
    if (field.options !== undefined) attributes.options = field.options;
    return { type: field.kind, id: field.id, attributes, validations: { required: field.required } };
  });
}

function confirmations(intake: CommunityIntake): YamlValue {
  return {
    type: "checkboxes",
    id: CONFIRMATIONS_FIELD_ID,
    attributes: { label: "Confirmations", options: intake.confirmations.map((label) => ({ label, required: true })) },
  };
}

/** The template path of a templated output. */
function templateOf(path: string): string {
  return `${TEMPLATES_DIRECTORY}/${path.replace(/^\.github\//u, "")}${TEMPLATE_SUFFIX}`;
}

/** Every generated file's text, keyed by its repository-relative path (a pure function of the templates and the facts). */
function renderCommunityFiles(templates: ReadonlyMap<string, string>, facts: CommunityFacts): ReadonlyMap<string, string> {
  const unused = [...templates.keys()].filter((path) => !TEMPLATED_FILES.some((file) => templateOf(file) === path));
  if (unused.length > 0) templateInvalid(TEMPLATES_DIRECTORY, `templates that name no generated file: ${unused.join(", ")}`);
  const slots = communitySlots(facts);
  const files = new Map<string, string>();
  for (const path of TEMPLATED_FILES) {
    const templatePath = templateOf(path);
    const template = templates.get(templatePath);
    if (template === undefined) templateInvalid(templatePath, `the template of ${path} is missing`);
    files.set(path, `<!-- ${generatedNotice(`${templatePath} and the community sources (docs/community/)`)} -->\n${fillTemplate(templatePath, template, slots)}`);
  }
  const { intake } = facts;
  const intakeNotice = [generatedNotice(`docs/community/intake.json (engine/src/workflow/community/health-files.ts)`)];
  for (const form of intake.issueForms) {
    files.set(`${ISSUE_FORMS_DIRECTORY}/${form.file}`, emitYaml({
      name: form.name,
      description: form.description,
      // A planned issue type is never named: GitHub would drop it.
      ...(isLive(form.typeStatus) ? { type: form.type } : {}),
      body: [{ type: "markdown", attributes: { value: `> [!WARNING]\n> ${intake.warning}` } }, ...formBody(form.fields), confirmations(intake)],
    }, intakeNotice));
  }
  files.set(`${ISSUE_FORMS_DIRECTORY}/config.yml`, emitYaml({
    blank_issues_enabled: false,
    contact_links: intake.contactLinks.map((link) => ({
      name: link.name,
      url: link.advisory === true ? advisoryUrl(facts) : categoryUrl(facts, link.category!),
      about: link.about,
    })),
  }, intakeNotice));
  for (const category of intake.discussionCategories) {
    // A planned category has no form: GitHub would offer a form for a category that does not exist.
    if (category.form === undefined || !isLive(category.status)) continue;
    files.set(`${DISCUSSION_FORMS_DIRECTORY}/${category.slug}.yml`, emitYaml({
      title: category.form.title,
      body: [{ type: "markdown", attributes: { value: `> [!WARNING]\n> ${intake.warning}` } }, ...formBody(category.form.fields)],
    }, intakeNotice));
  }
  return files;
}

function readTemplates(repositoryRoot: string): ReadonlyMap<string, string> {
  const directory = join(repositoryRoot, TEMPLATES_DIRECTORY);
  if (!existsSync(directory)) templateInvalid(TEMPLATES_DIRECTORY, "the templates folder is missing");
  const templates = new Map<string, string>();
  for (const name of readdirSync(directory, { recursive: true, encoding: "utf8" })) {
    const file = join(directory, name);
    if (lstatSync(file).isFile()) templates.set(`${TEMPLATES_DIRECTORY}/${name}`, readFileSync(file, "utf8"));
  }
  return templates;
}

/** Every file under `path` (repository-relative), recursively; a file is itself. */
function filesUnder(repositoryRoot: string, path: string): readonly string[] {
  const stat = lstatSync(join(repositoryRoot, path), { throwIfNoEntry: false });
  if (stat === undefined) return [];
  if (!stat.isDirectory()) return [path];
  return readdirSync(join(repositoryRoot, path)).sort().flatMap((name) => filesUnder(repositoryRoot, `${path}/${name}`));
}

/** Every file GitHub could read as a community health file or template, in the three locations (see the header). */
function healthFilesOnDisk(repositoryRoot: string): readonly string[] {
  return HEALTH_LOCATIONS.flatMap((location) => {
    const directory = join(repositoryRoot, location);
    if (!existsSync(directory)) return [];
    return readdirSync(directory)
      .filter((name) => (HEALTH_NAMES as readonly string[]).includes(name.toLowerCase().replace(/\..*$/u, "")))
      .flatMap((name) => filesUnder(repositoryRoot, location === "" ? name : `${location}/${name}`));
  });
}

/** Whether the tree carries any community surface: the sources folder, or any health file anywhere GitHub reads one. */
function hasCommunitySurface(repositoryRoot: string): boolean {
  return existsSync(join(repositoryRoot, COMMUNITY_DIRECTORY)) || healthFilesOnDisk(repositoryRoot).length > 0;
}

/**
 * Judges (and with `write`, rewrites) every generated community file of the
 * repository at `repositoryRoot`: a file whose text differs is rewritten; a
 * shadow (see the header) is drift — with `write`, the generator's own stale
 * output is deleted and a hand-made one refused (`community_shadow_file`).
 */
export function syncCommunityFiles(repositoryRoot: string, write: boolean): CommunityFilesReport {
  if (!hasCommunitySurface(repositoryRoot)) return Object.freeze({ status: "absent", converged: true, changed: [] });
  const files = renderCommunityFiles(readTemplates(repositoryRoot), readCommunityFacts(repositoryRoot));
  const shadows = healthFilesOnDisk(repositoryRoot).filter((path) => !files.has(path));
  if (write) {
    const handMade = shadows.filter((path) => !readFileSync(join(repositoryRoot, path), "utf8").includes(GENERATED_MARK));
    if (handMade.length > 0) {
      throw new HarnessError(
        `files GitHub would read as community health files or templates, which the generator did not write: ${handMade.join(", ")}. Move their content into docs/community/ (the sources) and delete them; harness sync never deletes a person's file`,
        "community_shadow_file",
        false,
        { count: handMade.length },
      );
    }
  }
  const changed: string[] = [...shadows];
  for (const [path, text] of files) {
    const file = join(repositoryRoot, path);
    if (existsSync(file) && readFileSync(file, "utf8") === text) continue;
    changed.push(path);
    if (!write) continue;
    mkdirSync(dirname(file), { recursive: true });
    const written = atomicWriteFile(file, text);
    if (!written.success) throw new HarnessError(`Failed to write ${path}: ${written.reason ?? "unknown error"}`, "community_file_write_failed");
  }
  if (write) for (const path of shadows) rmSync(join(repositoryRoot, path));
  changed.sort();
  if (changed.length === 0) return Object.freeze({ status: "current", converged: true, changed: [] });
  return Object.freeze(write ? { status: "regenerated", converged: true, changed } : { status: "stale", converged: false, changed });
}
