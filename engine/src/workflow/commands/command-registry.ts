/**
 * THE GENERATOR OF THE VERB REGISTRY (`registry.ts`): every file of this
 * folder that declares `export const COMMAND: HarnessCommand`, imported and
 * listed in verb order. `harness sync` writes it and `harness check` refuses a
 * stale or hand-edited one. The registry is wholly generated, so a merge
 * conflict on it resolves to either side and regenerates (#221).
 */
import { existsSync, readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";

import { readSourceView } from "../../../scripts/verification/source-view.ts";
import { atomicWriteFile } from "../../filesystem/atomic-write.ts";
import { HarnessError } from "../../kernel/errors.ts";
import { deepFreeze } from "../../kernel/integrity.ts";

/** The folder of the verb files and its generated registry, engine-relative. */
export const COMMANDS_FOLDER = "src/workflow/commands";
export const COMMAND_REGISTRY_FILE = "registry.ts";
const DECLARATION = /^export const COMMAND: HarnessCommand = \{\n {2}verb: "([a-z][a-z-]*)",/mu;

export type CommandRegistryReport = Readonly<{ status: "current" | "stale" | "regenerated"; converged: boolean; changed: readonly string[] }>;

/**
 * The verbs the files of `folder` declare, sorted: each file's code (comments
 * blanked, its strings kept: the verb is one) through the one source-view
 * owner. A verb declared in a file named otherwise is refused.
 */
export function declaredVerbs(folder: string): readonly string[] {
  return readdirSync(folder)
    .filter((name) => name.endsWith(".ts") && name !== COMMAND_REGISTRY_FILE)
    .flatMap((name) => {
      const match = readSourceView(join(folder, name)).matches(DECLARATION, "codeWithStrings")[0]?.match;
      if (match === undefined) return [];
      if (`${match[1]!}.ts` !== name) throw new HarnessError(`${name} declares the verb ${match[1]!}: a verb lives in the file named after it`, "command_registry_invalid");
      return [match[1]!];
    })
    .toSorted();
}

/** The registry's text for the verb files `folder` holds. */
export function commandRegistryText(folder: string): string {
  const verbs = declaredVerbs(folder);
  const binding = (verb: string): string => `${verb.replace(/-([a-z])/gu, (_, letter: string) => letter.toUpperCase())}Command`;
  return [
    "// GENERATED by `harness sync` from the verb files of this folder (command-registry.ts); do not edit.",
    'import type { HarnessCommand } from "./command.ts";',
    ...verbs.map((verb) => `import { COMMAND as ${binding(verb)} } from "./${verb}.ts";`),
    "",
    "/** Every harness verb, in verb order. */",
    "export const HARNESS_COMMANDS: readonly HarnessCommand[] = [",
    ...verbs.map((verb) => `  ${binding(verb)},`),
    "];",
    "",
  ].join("\n");
}

/** Judges (and with `write`, rewrites) the registry of the engine at `engineRoot`. */
export function syncCommandRegistry(engineRoot: string, write: boolean): CommandRegistryReport {
  const folder = join(engineRoot, COMMANDS_FOLDER);
  const path = join(folder, COMMAND_REGISTRY_FILE);
  const expected = commandRegistryText(folder);
  const current = existsSync(path) ? readFileSync(path, "utf8") : undefined;
  if (current === expected) return deepFreeze({ status: "current", converged: true, changed: [] });
  const changed = [`${COMMANDS_FOLDER}/${COMMAND_REGISTRY_FILE}`];
  if (!write) return deepFreeze({ status: "stale", converged: false, changed });
  const result = atomicWriteFile(path, expected);
  if (!result.success) throw new HarnessError(`could not write ${changed[0]!}: ${result.reason ?? "atomic write failed"}`, "command_registry_write_failed");
  return deepFreeze({ status: "regenerated", converged: true, changed });
}
