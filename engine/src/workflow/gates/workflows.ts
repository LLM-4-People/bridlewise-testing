export const WORKFLOW_DIRECTORY = GENERATED_WORKFLOW_FILES.directory;

/** The header every generated workflow starts with: what owns it, and that a hand edit is refused. */
export const GENERATED_HEADER = "# GENERATED by harness sync from engine/src/workflow/gates/ — edit the owner, never this file";

/** The engine CLI, from the repository root (every gate step is a harness command). */
const HARNESS = "node engine/src/cli.ts harness";
/** Where a job keeps its gate results before upload. */
const RESULTS_DIR = "${{ runner.temp }}/gate-results";

type Workflow = Readonly<Record<string, YamlValue>>;
type Step = Readonly<Record<string, YamlValue>>;

function uses(name: ActionName): Commented {
  const pin = ACTION_PINS[name];
  return new Commented(`${pin.repository}@${pin.sha}`, pin.version);
}

const PR_GROUP_CANCEL = "${{ github.event_name == 'pull_request' }}";
/** A pull request's runs share a group (a newer push supersedes); every other run is its own group, so nothing on `main` or in the queue is ever cancelled. */
function perEventConcurrency(prefix: string): Readonly<Record<string, YamlValue>> {
  return {
    group: `\${{ github.event_name == 'pull_request' && format('${prefix}-pr-{0}', github.event.pull_request.number) || format('${prefix}-{0}', github.run_id) }}`,
    "cancel-in-progress": PR_GROUP_CANCEL,
  };
}

function checkoutStep(): Step {
  return { name: "Check out", uses: uses("checkout"), with: { "persist-credentials": false } };
}

function setupNodeStep(): Step {
  return {
    name: "Set up Node",
    uses: uses("setup-node"),
    with: { "node-version-file": ".nvmrc", cache: "npm", "cache-dependency-path": "package-lock.json\nengine/package-lock.json\n" },
  };
}

/** The toolchain setup a job needs, in a fixed order, each once. */
const GCC_INSTALL = "sudo apt-get update\nsudo apt-get install -y gcc-14\n";
const TOOLCHAIN_STEPS: Readonly<Record<Toolchain, Step>> = {
  "gcc-14": { name: "Install the pinned compiler", run: GCC_INSTALL },
  hooks: { name: "Install the tracked hooks", run: "npm run bootstrap:hooks" },
  "engine-bundle": { name: "Build the engine bundle", run: "npm --prefix engine run build:bundle" },
  "guardian-binary": { name: "Build the guardian", run: "make -C engine/guardian all" },
  corpus: { name: "Fetch and verify the pinned corpus subset", run: "npm run corpus:fetch\nnpm run corpus:verify\n" },
};
const TOOLCHAIN_ORDER: readonly Toolchain[] = ["gcc-14", "hooks", "engine-bundle", "guardian-binary", "corpus"];

/**
 * A temporary root of the job's own, outside the checkout (D-19: a test run's
 * TMPDIR lies outside the safety floor). `runner.temp` is not available to a
 * job-level `env:`, so a step exports it.
 */
const TMPDIR_STEP: Step = { name: "Give the job its own temporary root", run: "mkdir -p \"$RUNNER_TEMP/tmp\"\necho \"TMPDIR=$RUNNER_TEMP/tmp\" >> \"$GITHUB_ENV\"\n" };

/**
 * Checkout, Node, both dependency trees, the config mode, the job's temporary
 * root, and the toolchain the job's gates need (deduplicated, in order). A
 * matrix job serving several suites runs a toolchain step only for the cells
 * whose gate needs it (`gatesNeeding`).
 */
function gateJobSetup(gates: readonly Gate[], engineOnly = false, matrix = false): readonly Step[] {
  const toolchain = TOOLCHAIN_ORDER.filter((tool) => gates.some((gate) => gate.toolchain.includes(tool)));
  return [
    checkoutStep(),
    setupNodeStep(),
    ...(engineOnly ? [] : [{ name: "Install web dependencies", run: "npm ci --no-audit --no-fund" }]),
    { name: "Install engine dependencies", run: "npm --prefix engine ci --no-audit --no-fund" },
    { name: "Enforce the self-protection config mode", run: "chmod 600 engine/bridlewise.config.json" },
    TMPDIR_STEP,
    ...toolchain.map((tool): Step => {
      const needing = gates.filter((gate) => gate.toolchain.includes(tool)).map((gate) => gate.id);
      return matrix && needing.length < gates.length
        ? { ...TOOLCHAIN_STEPS[tool], if: `\${{ contains(fromJSON('${JSON.stringify(needing)}'), matrix.gate) }}` }
        : TOOLCHAIN_STEPS[tool];
    }),
  ];
}

function uploadResultsStep(name: string): Step {
  return {
    name: "Upload the gate results",
    if: "${{ always() }}",
    uses: uses("upload-artifact"),
    with: { name, path: RESULTS_DIR, "if-no-files-found": "error", "retention-days": 90 },
  };
}

/** The CI workflow: plan, light, shards, action gates, seal. */
export function ciWorkflow(catalogue: readonly Gate[] = GATE_CATALOGUE): Workflow {
  const light = gatesOfClass("light", catalogue);
  const suites = gatesOfClass("suite", catalogue);
  const actions = gatesOfClass("action", catalogue);
  const jobs: Record<string, YamlValue> = {
    plan: {
      name: "plan",
      "runs-on": API_RUNNER,
      "timeout-minutes": 10,
      permissions: { contents: "read" },
      outputs: { cells: "${{ steps.plan.outputs.cells }}" },
      steps: [
        ...gateJobSetup([], true),
        { name: "Plan the gate cells", id: "plan", run: `${HARNESS} gates plan --out "$RUNNER_TEMP/gate-plan" --github-output "$GITHUB_OUTPUT"` },
        { name: "Upload the plan", uses: uses("upload-artifact"), with: { name: "gate-plan", path: "${{ runner.temp }}/gate-plan", "if-no-files-found": "error", "retention-days": 90 } },
      ],
    },
    light: {
      name: "light",
      needs: ["plan"],
      "runs-on": GATE_RUNNER,
      "timeout-minutes": 60,
      permissions: { contents: "read" },
      steps: [
        ...gateJobSetup(light),
        { name: "Download the plan", uses: uses("download-artifact"), with: { name: "gate-plan", path: "${{ runner.temp }}/gate-plan" } },
        ...light.map((gate): Step => ({
          name: gate.title,
          id: gate.id,
          background: true,
          run: `${HARNESS} gates run ${gate.id} --plan "$RUNNER_TEMP/gate-plan/plan.json" --out "$RUNNER_TEMP/gate-results"`,
        })),
        { name: "Wait for every light gate", "wait-all": null },
        uploadResultsStep("gate-results-light"),
      ],
    },
  };
  if (suites.length > 0) {
    jobs.shard = {
      name: "${{ matrix.title }}",
      needs: ["plan"],
      if: "${{ needs.plan.outputs.cells != '[]' }}",
      "runs-on": GATE_RUNNER,
      "timeout-minutes": 90,
      permissions: { contents: "read" },
      strategy: { "fail-fast": false, matrix: { include: "${{ fromJSON(needs.plan.outputs.cells) }}" } },
      steps: [
        ...gateJobSetup(suites, false, true),
        { name: "Download the plan", uses: uses("download-artifact"), with: { name: "gate-plan", path: "${{ runner.temp }}/gate-plan" } },
        {
          name: "Run the shard",
          env: { CELL: "${{ matrix.cell }}" },
          run: `${HARNESS} gates shard "$CELL" --plan "$RUNNER_TEMP/gate-plan/plan.json" --out "$RUNNER_TEMP/gate-results"`,
        },
        uploadResultsStep("gate-results-${{ matrix.cell }}"),
      ],
    };
  }
  for (const gate of actions) {
    const action = gate.action!;
    jobs[gate.id] = {
      name: gate.id,
      if: action.events.map((event) => `github.event_name == '${event}'`).join(" || "),
      "runs-on": GATE_RUNNER,
      "timeout-minutes": 15,
      permissions: { contents: "read" },
      steps: [checkoutStep(), { name: gate.title, uses: uses(action.uses), with: { ...action.with } }],
    };
  }
  const sealNeeds = Object.keys(jobs);
  jobs.seal = {
    name: "seal",
    needs: sealNeeds,
    if: "${{ always() }}",
    "runs-on": API_RUNNER,
    "timeout-minutes": 10,
    permissions: { contents: "read" },
    steps: [
      ...gateJobSetup([], true),
      { name: "Download the plan", uses: uses("download-artifact"), with: { name: "gate-plan", path: "${{ runner.temp }}/gate-plan" } },
      { name: "Download every gate result", uses: uses("download-artifact"), with: { pattern: "gate-results-*", path: "${{ runner.temp }}/gate-results", "merge-multiple": true } },
      {
        name: "Seal the receipt",
        env: { JOB_RESULTS: "${{ toJSON(needs) }}" },
        run: `${HARNESS} gates seal --plan "$RUNNER_TEMP/gate-plan/plan.json" --results "$RUNNER_TEMP/gate-results" --out "$RUNNER_TEMP/gate-receipt"`,
      },
      { name: "Upload the receipt", if: "${{ always() }}", uses: uses("upload-artifact"), with: { name: "gate-receipt", path: "${{ runner.temp }}/gate-receipt", "if-no-files-found": "error", "retention-days": 90 } },
    ],
  };
  return {
    name: "CI",
    on: {
      pull_request: { branches: ["main"] },
      merge_group: {},
      schedule: [{ cron: "17 3 * * *" }],
      workflow_dispatch: {},
    },
    permissions: { contents: "read" },
    concurrency: perEventConcurrency("ci"),
    jobs,
  };
}

/** CodeQL advanced setup: three languages, `security-extended`, on every event a land passes through. */
export function codeqlWorkflow(): Workflow {
  return {
    name: "CodeQL",
    on: {
      pull_request: { branches: ["main"] },
      merge_group: {},
      push: { branches: ["main"] },
      schedule: [{ cron: "29 4 * * 1" }],
      workflow_dispatch: {},
    },
    permissions: { contents: "read" },
    concurrency: perEventConcurrency("codeql"),
    jobs: {
      analyze: {
        name: "Analyze (${{ matrix.language }})",
        "runs-on": GATE_RUNNER,
        "timeout-minutes": 30,
        permissions: { actions: "read", contents: "read", packages: "read", "security-events": "write" },
        strategy: {
          "fail-fast": false,
          matrix: {
            include: [
              { language: "javascript-typescript", "build-mode": "none" },
              { language: "actions", "build-mode": "none" },
              { language: "c-cpp", "build-mode": "manual" },
            ],
          },
        },
        steps: [
          checkoutStep(),
          {
            name: "Initialize CodeQL",
            uses: uses("codeql-init"),
            with: { languages: "${{ matrix.language }}", "build-mode": "${{ matrix.build-mode }}", queries: "security-extended" },
          },
          { name: "Install the pinned compiler", if: "${{ matrix.build-mode == 'manual' }}", run: GCC_INSTALL },
          { name: "Build the guardian", if: "${{ matrix.build-mode == 'manual' }}", run: "make -C engine/guardian all" },
          { name: "Analyze", uses: uses("codeql-analyze"), with: { category: "/language:${{ matrix.language }}" } },
        ],
      },
    },
  };
}

/** The publisher: the Pages site on every land, in land order, never dropped. */
export function publishWorkflow(): Workflow {
  return {
    name: "Publish",
    on: {
      push: { branches: ["main"] },
      workflow_dispatch: { inputs: { product_ref: { description: "Product docs revision to mirror", required: false, default: "main", type: "string" } } },
    },
    permissions: { contents: "read" },
    concurrency: { group: "publish-main", "queue": "max" },
    jobs: {
      build: {
        name: "Build the site",
        if: "github.event.repository.visibility == 'public'",
        "runs-on": GATE_RUNNER,
        "timeout-minutes": 20,
        permissions: { contents: "read", pages: "read", actions: "read", "security-events": "read", "vulnerability-alerts": "read" },
        steps: [
          checkoutStep(),
          {
            name: "Check out the product docs",
            id: "product",
            uses: uses("checkout"),
            with: { repository: "LLM-4-People/bridlewise", ref: "${{ inputs.product_ref || 'main' }}", path: "product", "persist-credentials": false },
          },
          { name: "Set up Node", uses: uses("setup-node"), with: { "node-version-file": ".nvmrc" } },
          { name: "Configure Pages", id: "pages", uses: uses("configure-pages") },
          {
            name: "Assemble the mirror and floor",
            env: { BASE_PATH: "${{ steps.pages.outputs.base_path }}" },
            run: "node scripts/assemble-floor-site.mjs --product product/docs --testing . --out .site --baseurl \"$BASE_PATH\"",
          },
          {
            name: "Generate floor data",
            env: { GH_TOKEN: "${{ github.token }}" },
            run: "node scripts/build-floor-data.mjs --testing . --product product --out .site/floor/data",
          },
          {
            name: "Build with Jekyll",
            uses: uses("jekyll-build-pages"),
            with: { source: "./.site", destination: "./_site", build_revision: "${{ steps.product.outputs.commit }}" },
          },
          {
            name: "Check the built site has no broken internal links",
            env: { BASE_PATH: "${{ steps.pages.outputs.base_path }}" },
            run: "node scripts/floor/site-links.mjs --site _site --baseurl \"$BASE_PATH\"",
          },
          { name: "Check design coverage", run: "node scripts/floor/design-coverage.mjs --site _site" },
          { name: "Upload the Pages artifact", uses: uses("upload-pages-artifact"), with: { path: "./_site", "include-hidden-files": true } },
        ],
      },
      deploy: {
        name: "Deploy to GitHub Pages",
        if: "github.event.repository.visibility == 'public'",
        needs: ["build"],
        "runs-on": API_RUNNER,
        "timeout-minutes": 10,
        permissions: { pages: "write", "id-token": "write", actions: "read" },
        environment: { name: "github-pages", url: "${{ steps.deployment.outputs.page_url }}" },
        steps: [{ name: "Deploy", id: "deployment", uses: uses("deploy-pages") }],
      },
    },
  };
}

