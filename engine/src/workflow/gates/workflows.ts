/**
 * THE WORKFLOW GENERATOR — every file under `.github/workflows/` is this
 * module's output of the gate catalogue (`catalogue.ts`); nothing in that
 * folder is hand-written (github-only §5.1).
 *
 * `harness sync` writes the files (`syncGeneratedWorkflows`, the regenerate
 * arm in `harness-commands.ts`) and `harness check` refuses a file that is not
 * byte-equal to this output — a hand edit, a stale file, or a workflow file no
 * generator owns. The folder holds exactly {@link GENERATED_WORKFLOW_PATHS}.
 *
 * WHAT IS GENERATED (trust split, §5.2):
 *   - `ci.yml`: the untrusted compute. `plan` lists the cells, the
 *     `light` job runs every light gate in turn, the `shard`
 *     matrix runs the suites' CPU-balanced shards, the action gates run as
 *     their own jobs, and `seal` merges every result into the one receipt and
 *     fails unless every required gate passed. Its token reads contents only;
 *     it holds no secret and no `id-token`.
 *   - `codeql.yml`: CodeQL advanced setup (JavaScript/TypeScript, Actions,
 *     C/C++; `security-extended`), on pull requests, the merge queue, `main`
 *     and weekly.
 *   - `pages.yml`: the docs site, built on every pull request and land and
 *     deployed from `main` only, serialised in commit order (`queue: max`,
 *     never cancelled).
 *   - `audit.yml`: the scheduled audit (OpenSSF Scorecard).
 *
 * LINTS THE GENERATOR ENFORCES ON ITS OWN OUTPUT (`lintWorkflow`): every
 * `uses:` is a full-SHA pin from `ACTION_PINS`; every workflow and job states
 * `permissions:`; no `${{ … }}` expression inside a `run:` (untrusted text
 * reaches a step through `env:` only); no `pull_request_target`; every
 * workflow a pull request runs also runs on `merge_group`, both unfiltered
 * (a filter would leave a required check pending on the skipped pull
 * requests), and `push` names only `main`; a `main` run is never cancelled (a
 * pull request's group cancels, every other event's group is its own run or
 * queues with `queue: max`); no two workflows share a concurrency group
 * prefix (`lintWorkflowSet`: they would cancel each other's runs).
 */
