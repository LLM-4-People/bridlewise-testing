type WorkflowFile = (typeof GENERATED_WORKFLOW_FILES.files)[number];

/** The builder of each generated workflow file (the file list is `GENERATED_WORKFLOW_FILES`, the one declaration). */
const WORKFLOW_BUILDERS: Readonly<Record<WorkflowFile, () => Workflow>> = deepFreeze({
  "audit.yml": auditWorkflow,
  "ci.yml": () => ciWorkflow(),
  "codeql.yml": codeqlWorkflow,
  "publish.yml": publishWorkflow,
});

/** The generated workflow files, repository-relative. The folder holds exactly these. */
export const GENERATED_WORKFLOW_PATHS: readonly string[] = Object.freeze(
  GENERATED_WORKFLOW_FILES.files.map((name) => `${WORKFLOW_DIRECTORY}/${name}`).toSorted(),
);

const EXPRESSION = /\$\{\{/u;

/** Refuses a workflow document that breaks a generator lint (the module header lists them). */
export function lintWorkflow(name: string, workflow: Workflow): void {
  const refuse = (message: string): never => {
    throw new InputError(`generated workflow ${name}: ${message}`, "workflow_lint_refused");
  };
  const on = workflow.on as Readonly<Record<string, YamlValue>>;
  if ("pull_request_target" in on) refuse("pull_request_target is never used");
  if ("pull_request" in on && !("merge_group" in on)) refuse("a workflow that runs on pull_request also runs on merge_group");
  if (workflow.permissions === undefined) refuse("no workflow-level permissions");
  const concurrency = workflow.concurrency as Readonly<Record<string, YamlValue>> | undefined;
  if (concurrency === undefined) refuse("no concurrency block");
  const cancel = concurrency!["cancel-in-progress"];
  if (cancel !== undefined && cancel !== PR_GROUP_CANCEL) refuse("only a pull request's group cancels");
  if (cancel === undefined && concurrency!.queue !== "max") refuse("a shared group without cancel queues with queue: max (the default single slot cancels a pending run)");
  const jobs = workflow.jobs as Readonly<Record<string, Readonly<Record<string, YamlValue>>>>;
  for (const [jobId, job] of Object.entries(jobs)) {
    if (job.permissions === undefined) refuse(`job ${jobId} states no permissions`);
    for (const step of (job.steps ?? []) as readonly Step[]) {
      const run = step.run;
      if (typeof run === "string" && EXPRESSION.test(run)) refuse(`job ${jobId} step ${String(step.name)}: an expression inside run: (pass it through env:)`);
      const action = step.uses;
      if (action !== undefined) {
        if (!(action instanceof Commented)) refuse(`job ${jobId}: an action is used without its pin comment`);
        const pinned = Object.values(ACTION_PINS).some((pin) => (action as Commented).value === `${pin.repository}@${pin.sha}`);
        if (!pinned) refuse(`job ${jobId}: ${(action as Commented).value} is not a pin of ACTION_PINS`);
      }
    }
  }
}

/** The bytes of one generated workflow (header, then the YAML), linted. */
export function workflowText(name: string): string {
  const build = (WORKFLOW_BUILDERS as Readonly<Record<string, () => Workflow>>)[name];
  if (build === undefined) throw new InputError(`no generated workflow ${name}`, "workflow_unknown");
  const workflow = build();
  lintWorkflow(name, workflow);
  return `${GENERATED_HEADER}\n${emitYaml(workflow)}`;
}

export type GeneratedWorkflowsReport = Readonly<{
  allCurrent: boolean;
  status: "current" | "regenerated" | "stale";
  changed: readonly string[];
}>;

/**
 * Judges (and with `write`, rewrites) `.github/workflows/` of the repository
 * at `repositoryRoot`: every generated file byte-equal to its generator's
 * output, and no other file in the folder. With `write`, a stale or absent
 * file is written and a foreign file is deleted — the folder is wholly
 * generated, so a file no generator owns is drift, never a hand-kept extra.
 */
export function syncGeneratedWorkflows(repositoryRoot: string, write: boolean, remove: (absolutePath: string) => void = defaultRemove): GeneratedWorkflowsReport {
  const directory = join(repositoryRoot, WORKFLOW_DIRECTORY);
  const expected = new Map(GENERATED_WORKFLOW_PATHS.map((path) => [path, workflowText(path.slice(WORKFLOW_DIRECTORY.length + 1))]));
  const present = existsSync(directory) ? readdirSync(directory).map((name) => `${WORKFLOW_DIRECTORY}/${name}`) : [];
  const stale = [...expected].filter(([path, text]) => {
    const absolute = join(repositoryRoot, path);
    return !existsSync(absolute) || readFileSync(absolute, "utf8") !== text;
  });
  const foreign = present.filter((path) => !expected.has(path));
  const changed = Object.freeze([...stale.map(([path]) => path), ...foreign].toSorted());
  if (changed.length === 0) return Object.freeze({ allCurrent: true, status: "current", changed });
  if (!write) return Object.freeze({ allCurrent: false, status: "stale", changed });
  mkdirSync(directory, { recursive: true });
  for (const [path, text] of stale) {
    const written = atomicWriteFile(join(repositoryRoot, path), text);
    if (!written.success) throw new HarnessError(`Failed to write ${path}: ${written.reason ?? "unknown error"}`, "workflow_write_failed");
  }
  for (const path of foreign) remove(join(repositoryRoot, path));
  return Object.freeze({ allCurrent: true, status: "regenerated", changed });
}

function defaultRemove(absolutePath: string): void {
  rmSync(absolutePath);
}
