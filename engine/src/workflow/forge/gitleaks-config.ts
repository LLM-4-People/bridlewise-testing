/**
 * THE ORACLE'S CONFIGURATION, GENERATED FROM THE ONE CATALOGUE — the
 * `.gitleaks.toml` the history importer hands its independent oracle
 * (`history-import.ts`, github-only §8.2/§8.3). It used to be a hand-written
 * third copy of the credential formats with its own placeholder allowlist;
 * now it is a projection of `SECRET_TEXT_SIGNAL_CATALOG` and nothing else:
 *
 * - gitleaks' OWN default rules (`[extend] useDefault = true`): the oracle's
 *   independent half, which exists to find a format the catalogue lacks;
 * - one rule per catalogue row whose admission pattern RE2 (gitleaks' Go
 *   engine) can express, id `bridlewise-<row id>`: the catalogue's formats
 *   checked again by a second regex engine, so a purge the catalogue believes
 *   complete is re-checked independently;
 * - every row RE2 cannot express (a lookaround, a JavaScript-only escape) is
 *   NAMED in the file's header with the reason — never dropped silently and
 *   never approximated: the catalogue scan enforces it.
 *
 * There is no allowlist: a fixture credential is assembled at runtime from
 * catalogue-owned parts, so the tree holds none, and an imported history's
 * old fixtures are purged like any other hit.
 */
import { SECRET_TEXT_SIGNAL_CATALOG } from "../../privacy/secret-signals.ts";
import { deepFreeze } from "../../kernel/integrity.ts";

/** The id prefix of a catalogue row's projected rule (an oracle hit under it is the catalogue's own format). */
export const GITLEAKS_CATALOGUE_RULE_PREFIX = "bridlewise-";

type CatalogueRow = Readonly<{ id: string; description: string; admission: RegExp }>;

export type GitleaksRule = Readonly<{ id: string; description: string; regex: string }>;
export type GitleaksProjection = Readonly<{
  rules: readonly GitleaksRule[];
  notProjected: readonly Readonly<{ id: string; reason: string }>[];
}>;

/** Constructs RE2 refuses, each with the reason the header names. */
const RE2_UNSUPPORTED: readonly Readonly<{ pattern: RegExp; reason: string }>[] = deepFreeze([
  { pattern: /\(\?<?[=!]/u, reason: "a lookaround (RE2 has none)" },
  { pattern: /\\[1-9]|\\k</u, reason: "a backreference (RE2 has none)" },
  { pattern: /\\u|\\c/u, reason: "a JavaScript-only escape" },
]);

/** The inline flags RE2 spells as JavaScript does; `u`, `g`, `y` and `d` change nothing RE2 decides. */
const RE2_FLAGS = new Set(["i", "m", "s"]);
const IGNORED_FLAGS = new Set(["u", "g", "y", "d"]);

/** Why `regex` cannot be projected to RE2, or `undefined` when it can. */
function re2Refusal(regex: RegExp): string | undefined {
  for (const { pattern, reason } of RE2_UNSUPPORTED) if (pattern.test(regex.source)) return reason;
  const unknown = [...regex.flags].filter((flag) => !RE2_FLAGS.has(flag) && !IGNORED_FLAGS.has(flag));
  if (unknown.length > 0) return `the flag(s) ${unknown.join("")} (RE2 has no equivalent)`;
  if (regex.source.includes("'''")) return "a TOML literal-string delimiter in the pattern";
  return undefined;
}

/** `regex` in RE2's spelling: its inline flags, then its source. */
function re2Source(regex: RegExp): string {
  const flags = [...regex.flags].filter((flag) => RE2_FLAGS.has(flag)).join("");
  return `${flags.length > 0 ? `(?${flags})` : ""}${regex.source}`;
}

/** Every catalogue row's projection (rules in catalogue order) and every row left to the catalogue scan, with why. */
export function gitleaksProjection(catalog: readonly CatalogueRow[] = SECRET_TEXT_SIGNAL_CATALOG): GitleaksProjection {
  const rules: GitleaksRule[] = [];
  const notProjected: { id: string; reason: string }[] = [];
  for (const row of catalog) {
    const refusal = re2Refusal(row.admission);
    if (refusal === undefined) rules.push({ id: `${GITLEAKS_CATALOGUE_RULE_PREFIX}${row.id}`, description: row.description, regex: re2Source(row.admission) });
    else notProjected.push({ id: row.id, reason: refusal });
  }
  return deepFreeze({ rules, notProjected });
}

/** A TOML basic string (the description: quotes and backslashes escaped). */
function tomlString(value: string): string {
  return JSON.stringify(value);
}

/** The whole generated `.gitleaks.toml` (deterministic: the catalogue's order, no timestamp). */
export function gitleaksConfigText(catalog: readonly CatalogueRow[] = SECRET_TEXT_SIGNAL_CATALOG): string {
  const projection = gitleaksProjection(catalog);
  const lines = [
    "# GENERATED by harness sync from the secret catalogue (engine/src/privacy/secret-signals.ts,",
    "# projected by engine/src/workflow/forge/gitleaks-config.ts). Do not edit: change the catalogue.",
    "#",
    "# The history importer's independent oracle (harness forge import-history): gitleaks' own",
    "# default rules, plus every catalogue row RE2 can express. A hit only gitleaks finds is a",
    "# refusal until the catalogue has a row for it; this file never decides what is purged.",
  ];
  if (projection.notProjected.length > 0) {
    lines.push("#", "# Not projected (the catalogue scan enforces them):");
    for (const row of projection.notProjected) lines.push(`#   ${row.id}: ${row.reason}`);
  }
  lines.push("", `title = ${tomlString("Bridlewise history-import oracle")}`, "", "[extend]", "useDefault = true");
  for (const rule of projection.rules) {
    lines.push("", "[[rules]]", `id = ${tomlString(rule.id)}`, `description = ${tomlString(rule.description)}`, `regex = '''${rule.regex}'''`);
  }
  return `${lines.join("\n")}\n`;
}
