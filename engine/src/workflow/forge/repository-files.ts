/**
 * THE FORGE'S IN-TREE RENDERS outside `.github/forge/` (runbook P2.5): the
 * Dependabot file and CODEOWNERS, each a pure function of its owners, and
 * the tree facts the declarations read (the actions the workflows pin, the
 * lockfiles Dependabot must cover).
 *
 * - `.github/dependabot.yml`: one entry per declared package root, grouped
 *   (minor and patch together), with the declared cooldowns and pull-request
 *   limit. BROAD by construction: every tracked lockfile outside a frozen
 *   prefix must be a declared root, and every declared root must hold its
 *   lockfile, or the render is refused (`forge_declaration_invalid`).
 * - `.github/CODEOWNERS`: routing only (`require_code_owner_review` stays
 *   off): every path to the verifying team(s) and the maintainers the role
 *   table names (`docs/community/roles.json`). Apps cannot be code owners.
 */
import { posix } from "node:path";

import type { CommunityRoles } from "../community/sources.ts";
import type { TreeReader } from "../../git/tree-reader.ts";
import { emitYaml } from "../../text/yaml-emit.ts";
import { ForgeError } from "./codes.ts";
import type { ForgeSettings } from "./forge-config.ts";

export const DEPENDABOT_FILE = ".github/dependabot.yml";
export const CODEOWNERS_FILE = ".github/CODEOWNERS";

const HEADER_TEXT = "GENERATED by harness sync from engine/src/workflow/forge/repository-files.ts and the forge configuration; never edit by hand.";
const HEADER = `# ${HEADER_TEXT}`;

/** What the declarations read from the tree. */
export type ForgeTreeFacts = Readonly<{
  /** Every `uses:` reference of the workflows. */
  workflowActions: readonly string[];
  /** The directories (`/`, `/engine`) of every tracked lockfile, per ecosystem. */
  lockfileDirectories: Readonly<Record<"npm" | "cargo", readonly string[]>>;
  /** Whether the tree holds workflows (the `github-actions` ecosystem's root). */
  hasWorkflows: boolean;
}>;

/** A mapping key line (after any `- ` list markers): its key and the rest of the line. */
const KEY_LINE = /^((?:-[ \t]+)*)([A-Za-z_][\w-]*)[ \t]*:(?:[ \t]+(.*))?$/u;
/** A block scalar header (`|`, `>-`, `|2+`, with an optional comment). */
const BLOCK_HEADER = /^[|>][0-9+-]{0,3}[ \t]*(?:#.*)?$/u;
/** A plain action reference: `owner/repo[/path]@ref`, `./local`, or `docker://image`. */
const ACTION_REFERENCE = /^(?:\.\/[\w./-]+|docker:\/\/[\w./:@-]+|[\w.-]+\/[\w./-]+@[\w./-]+)$/u;

/**
 * THE `uses:` KEYS of a workflow, read structurally: only a mapping key named
 * `uses` counts. A block scalar (`run: |` and its more-indented lines) and a
 * quoted scalar that spans lines are skipped whole, so text inside a `run:`
 * script can never widen the allowed actions. A form this reader does not
 * decide (a flow mapping or an anchor or alias carrying `uses`, a value that is
 * not a plain action reference) is refused, never guessed.
 */
export function workflowUsesOf(text: string, path: string): readonly string[] {
  const uses: string[] = [];
  let blockIndent: number | undefined;
  let openQuote: string | undefined;
  const refuse = (line: number, why: string): never => {
    throw new ForgeError("forge_declaration_invalid", `${path}:${String(line)}: ${why}; the allowed actions are read from parsed \`uses:\` keys only.`, { path, line });
  };
  for (const [index, raw] of text.split("\n").entries()) {
    const line = raw.replace(/\r$/u, "");
    if (openQuote !== undefined) {
      if (line.includes(openQuote)) openQuote = undefined;
      continue;
    }
    if (line.trim() === "") continue;
    const indent = line.length - line.trimStart().length;
    if (blockIndent !== undefined) {
      if (indent > blockIndent) continue;
      blockIndent = undefined;
    }
    const content = line.trimStart();
    if (content.startsWith("#")) continue;
    const key = KEY_LINE.exec(content);
    if (key === null) {
      if (/(?:^|[\s{,])uses[ \t]*:/u.test(content)) refuse(index + 1, "a `uses` this reader does not decide (a flow mapping)");
      continue;
    }
    const value = (key[3] ?? "").trim();
    if (BLOCK_HEADER.test(value)) { blockIndent = indent + key[1]!.length; continue; }
    const quote = value[0];
    if ((quote === "\"" || quote === "'") && value.slice(1).indexOf(quote) === -1) { openQuote = quote; continue; }
    if (key[2] !== "uses") continue;
    const reference = value.replace(/[ \t]+#.*$/u, "").replace(/^(["'])(.*)\1$/u, "$2");
    if (!ACTION_REFERENCE.test(reference)) refuse(index + 1, `\`uses: ${reference}\` is not a plain action reference`);
    uses.push(reference);
  }
  return Object.freeze(uses);
}
const LOCKFILES: Readonly<Record<string, "npm" | "cargo">> = { "package-lock.json": "npm", "Cargo.lock": "cargo" };

/** The tree facts, from the files the repository owns. */
export function forgeTreeFacts(tree: TreeReader, settings: ForgeSettings): ForgeTreeFacts {
  const workflows = tree.paths().filter((path) => /^\.github\/workflows\/[^/]+\.ya?ml$/u.test(path));
  tree.prefetch(workflows);
  const workflowActions = workflows.flatMap((path) => workflowUsesOf(tree.text(path) ?? "", path));
  const directories: Record<"npm" | "cargo", string[]> = { npm: [], cargo: [] };
  for (const path of tree.paths()) {
    const ecosystem = LOCKFILES[posix.basename(path)];
    if (ecosystem === undefined || path.split("/").includes("node_modules") || settings.dependabot.frozenPrefixes.some((prefix) => path.startsWith(prefix))) continue;
    const directory = posix.dirname(path);
    directories[ecosystem].push(directory === "." ? "/" : `/${directory}`);
  }
  return Object.freeze({ workflowActions: Object.freeze(workflowActions), lockfileDirectories: Object.freeze({ npm: Object.freeze(directories.npm.sort()), cargo: Object.freeze(directories.cargo.sort()) }), hasWorkflows: workflows.length > 0 });
}

/** The Dependabot file (see the header). */
export function dependabotFile(settings: ForgeSettings, facts: ForgeTreeFacts): string {
  const { dependabot } = settings;
  for (const ecosystem of ["npm", "cargo"] as const) {
    const declared = dependabot.packages.filter((entry) => entry.ecosystem === ecosystem).map((entry) => entry.directory).sort();
    const found = facts.lockfileDirectories[ecosystem];
    const missing = found.filter((directory) => !declared.includes(directory));
    const absent = declared.filter((directory) => !found.includes(directory));
    if (missing.length > 0 || absent.length > 0) {
      throw new ForgeError("forge_declaration_invalid", `Dependabot's ${ecosystem} roots differ from the tracked lockfiles: undeclared ${missing.join(", ") || "none"}; declared without a lockfile ${absent.join(", ") || "none"}.`, { ecosystem, undeclared: missing, absent });
    }
  }
  const actions = dependabot.packages.filter((entry) => entry.ecosystem === "github-actions");
  if (facts.hasWorkflows !== actions.length > 0) {
    throw new ForgeError("forge_declaration_invalid", "Dependabot's github-actions entry must exist exactly when the tree has workflows.", {});
  }
  const { schedule } = dependabot;
  // THE one YAML emitter writes it (no template): key order is the order stated here.
  return emitYaml({
    version: 2,
    updates: dependabot.packages.map((entry) => ({
      "package-ecosystem": entry.ecosystem,
      directory: entry.directory,
      schedule: { interval: schedule.interval, ...(schedule.interval === "weekly" ? { day: schedule.day } : {}), time: schedule.time, timezone: schedule.timezone },
      "open-pull-requests-limit": dependabot.openPullRequestsLimit,
      cooldown: { "default-days": dependabot.cooldownDays, "semver-major-days": dependabot.majorCooldownDays },
      groups: { [entry.group]: { "applies-to": "version-updates", patterns: ["*"], "update-types": ["minor", "patch"] } },
    })),
  }, [HEADER_TEXT]);
}

/** CODEOWNERS (see the header). */
export function codeownersFile(settings: ForgeSettings, roles: CommunityRoles): string {
  const verifying = new Set(roles.roles.filter((role) => role.verifies).map((role) => role.id));
  const teams = roles.roles.filter((role) => verifying.has(role.id) && role.team !== null).map((role) => `@${settings.organization}/${role.team!}`);
  const people = roles.members.filter((member) => verifying.has(member.role) && roles.roles.find((role) => role.id === member.role)?.team === null).map((member) => `@${member.login}`);
  const owners = [...teams, ...people.sort()];
  if (owners.length === 0) throw new ForgeError("forge_declaration_invalid", "The role table names no verifying team or member to route reviews to.", {});
  return `${HEADER}\n# Routing only: review requests go to the verifying roles of docs/community/roles.json.\n* ${owners.join(" ")}\n`;
}
