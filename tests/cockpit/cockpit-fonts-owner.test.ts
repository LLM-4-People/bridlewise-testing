const TOKENS = "src/cockpit/tokens.css";
const FONT_DIR = "public/fonts";
const LOCK = "public/fonts/fonts.lock.json";
const FONT_FILE = /\.(?:woff2?|ttf|otf|eot)(?:[?#][^"'`)\s]*)?$/iu;
/** A remote stylesheet: a font source in disguise (it can carry `@font-face` from anywhere). */
const STYLESHEET_FILE = /\.css(?:[?#][^"'`)\s]*)?$/iu;
/** The CSS-wide keywords a `font-family` or `font` may take instead of a `--face-*` token. */
const CSS_WIDE = /^(?:inherit|initial|unset|revert|revert-layer)$/iu;

// ── The parsers ────────────────────────────────────────────────────────────

type CssUnit = Readonly<{ kind: "font-face" | "import" | "url"; value: string; at: number }>;

/** A CSS text tokenized into its @font-face blocks, @import rules and url() references (comments and strings respected). */
export function cssUnits(css: string): CssUnit[] {
  const units: CssUnit[] = [];
  let i = 0;
  const readString = (quote: string): string => {
    let out = "";
    i += 1;
    while (i < css.length && css[i] !== quote) {
      if (css[i] === "\\") { out += css[i + 1] ?? ""; i += 2; continue; }
      out += css[i]; i += 1;
    }
    i += 1;
    return out;
  };
  while (i < css.length) {
    if (css.startsWith("/*", i)) { const end = css.indexOf("*/", i + 2); i = end < 0 ? css.length : end + 2; continue; }
    const ch = css[i]!;
    if (ch === '"' || ch === "'") { readString(ch); continue; }
    if (ch === "@") {
      const name = /^@([\w-]+)/u.exec(css.slice(i))?.[1]?.toLowerCase() ?? "";
      if (name === "font-face") { units.push({ kind: "font-face", value: "", at: i }); i += 10; continue; }
      if (name === "import") {
        i += 7;
        while (/\s/u.test(css[i] ?? "")) i += 1;
        const q = css[i];
        if (q === '"' || q === "'") units.push({ kind: "import", value: readString(q), at: i });
        else if (/^url\(/iu.test(css.slice(i))) {
          i += 4;
          while (/\s/u.test(css[i] ?? "")) i += 1;
          const inner = css[i] === '"' || css[i] === "'" ? readString(css[i]!) : css.slice(i, css.indexOf(")", i)).trim();
          units.push({ kind: "import", value: inner, at: i });
        }
        continue;
      }
    }
    if ((ch === "u" || ch === "U") && /^url\(/iu.test(css.slice(i)) && !/[\w-]/u.test(css[i - 1] ?? "")) {
      i += 4;
      while (/\s/u.test(css[i] ?? "")) i += 1;
      const q = css[i];
      const value = q === '"' || q === "'" ? readString(q) : css.slice(i, Math.max(i, css.indexOf(")", i))).trim();
      units.push({ kind: "url", value, at: i });
      continue;
    }
    i += 1;
  }
  return units;
}

/**
 * The `<style>` bodies, the `<script>` bodies and the markup (everything else,
 * comments removed) of an HTML or Svelte file, cut by index, case-insensitively.
 */
export function splitMarkup(source: string): Readonly<{ styles: string[]; scripts: string[]; scriptTags: string[]; markup: string }> {
  const lower = source.toLowerCase();
  const styles: string[] = [];
  const scripts: string[] = [];
  /** Each script's opening tag (its attributes: a `src` is a reference the build follows). */
  const scriptTags: string[] = [];
  let markup = "";
  let i = 0;
  while (i < source.length) {
    const next = [lower.indexOf("<style", i), lower.indexOf("<script", i), lower.indexOf("<!--", i)].filter((at) => at >= 0).sort((a, b) => a - b)[0];
    if (next === undefined) { markup += source.slice(i); break; }
    markup += `${source.slice(i, next)} `;
    if (lower.startsWith("<!--", next)) {
      const end = lower.indexOf("-->", next + 4);
      i = end < 0 ? source.length : end + 3;
      continue;
    }
    const name = lower.startsWith("<style", next) ? "style" : "script";
    const open = lower.indexOf(">", next);
    const close = open < 0 ? -1 : lower.indexOf(`</${name}`, open);
    const body = open < 0 ? "" : source.slice(open + 1, close < 0 ? source.length : close);
    (name === "style" ? styles : scripts).push(body);
    if (name === "script" && open >= 0) scriptTags.push(source.slice(next, open + 1));
    const after = close < 0 ? -1 : lower.indexOf(">", close);
    i = after < 0 ? source.length : after + 1;
  }
  return { styles, scripts, scriptTags, markup };
}

/** Every `<link>` tag of a markup text, its attributes lower-cased by name. */
export function linkTags(markup: string): Readonly<Record<string, string>>[] {
  return [...markup.matchAll(/<link\b([^>]*)>/giu)].map((tag) => tagAttributes(tag[1]!));
}

/** The attributes of one tag's text, lower-cased by name. */
export function tagAttributes(tag: string): Readonly<Record<string, string>> {
  const attributes: Record<string, string> = {};
  for (const a of tag.matchAll(/([\w:-]+)\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s"'>]+))/gu)) attributes[a[1]!.toLowerCase()] = a[2] ?? a[3] ?? a[4] ?? "";
  return attributes;
}

/** The string literals of a script (single, double and template quotes; comments skipped), and its import specifiers. */
export function scriptStrings(code: string): Readonly<{ strings: string[]; code: string }> {
  const strings: string[] = [];
  let i = 0;
  let bare = "";
  while (i < code.length) {
    if (code.startsWith("//", i)) { const end = code.indexOf("\n", i); i = end < 0 ? code.length : end; continue; }
    if (code.startsWith("/*", i)) { const end = code.indexOf("*/", i + 2); i = end < 0 ? code.length : end + 2; continue; }
    const ch = code[i]!;
    if (ch === '"' || ch === "'" || ch === "`") {
      let out = "";
      i += 1;
      while (i < code.length && code[i] !== ch) {
        if (code[i] === "\\") { out += code[i + 1] ?? ""; i += 2; continue; }
        out += code[i]; i += 1;
      }
      i += 1;
      strings.push(out);
      bare += " \"\" ";
      continue;
    }
    bare += ch;
    i += 1;
  }
  return { strings, code: bare };
}

// ── The judgement ─────────────────────────────────────────────────────────

/** The declared font sources: the url()s of the owner's @font-face blocks. */
export function declaredSources(ownerCss: string): ReadonlySet<string> {
  const units = cssUnits(ownerCss);
  const sources = new Set<string>();
  units.forEach((unit, index) => {
    if (unit.kind !== "url") return;
    const face = units.slice(0, index).reverse().find((u) => u.kind === "font-face");
    if (face !== undefined && ownerCss.slice(face.at, unit.at).indexOf("}") < 0) sources.add(unit.value);
  });
  return sources;
}

const isRemote = (value: string): boolean => /^(?:[a-z][a-z0-9+.-]*:)?\/\//iu.test(value.trim());

/** A file's kind, by extension: how the guard parses it. A kind outside this table is refused, never skipped. */
const KINDS: Readonly<Record<string, "css" | "markup" | "script" | "inert">> = {
  ".css": "css", ".scss": "css", ".sass": "css", ".less": "css", ".pcss": "css", ".postcss": "css",
  ".html": "markup", ".htm": "markup", ".svelte": "markup", ".svg": "markup",
  ".ts": "script", ".mts": "script", ".cts": "script", ".tsx": "script",
  ".js": "script", ".mjs": "script", ".cjs": "script", ".jsx": "script",
  // Bytes the browser never parses as style or script: data (a manifest, the font lock; turning a string of it
  // into a font load needs a runtime loader, which is refused), images, the font files themselves, prose.
  ".json": "inert", ".webmanifest": "inert",
  ".woff2": "inert", ".woff": "inert", ".ttf": "inert", ".otf": "inert", ".png": "inert", ".jpg": "inert", ".jpeg": "inert",
  ".gif": "inert", ".webp": "inert", ".avif": "inert", ".ico": "inert", ".md": "inert", ".txt": "inert",
};

/** The text of a stylesheet with its comments blanked (strings kept, offsets kept). */
function cssWithoutComments(css: string): string {
  let out = "";
  let i = 0;
  while (i < css.length) {
    if (css.startsWith("/*", i)) {
      const end = css.indexOf("*/", i + 2);
      const stop = end < 0 ? css.length : end + 2;
      out += css.slice(i, stop).replace(/[^\n]/gu, " ");
      i = stop;
      continue;
    }
    const ch = css[i]!;
    if (ch === '"' || ch === "'") {
      let j = i + 1;
      while (j < css.length && css[j] !== ch) j += css[j] === "\\" ? 2 : 1;
      out += css.slice(i, j + 1);
      i = j + 1;
      continue;
    }
    out += ch;
    i += 1;
  }
  return out;
}

/** Every font declaration of a stylesheet: `font-family`, `font` and `--face-*` properties, and whether each sits in an `@font-face` block. */
export function fontDeclarations(css: string): { property: string; value: string; inFace: boolean }[] {
  const text = cssWithoutComments(css);
  const faces = cssUnits(css).filter((u) => u.kind === "font-face").map((u) => [u.at, text.indexOf("}", u.at)] as const);
  return [...text.matchAll(/(?:^|[;{\s])(--face-[\w-]+|font-family|font)\s*:\s*([^;{}]*)/giu)].map((m) => ({
    property: m[1]!.toLowerCase(),
    value: m[2]!.trim(),
    inFace: faces.some(([from, to]) => m.index! > from && (to < 0 || m.index! < to)),
  }));
}

/** Each `@font-face` block's family and style (`normal` when the block names none). */
export function faceBlocks(css: string): { family: string; style: string }[] {
  const text = cssWithoutComments(css);
  return cssUnits(css).filter((u) => u.kind === "font-face").map((u) => {
    const end = text.indexOf("}", u.at);
    const block = text.slice(u.at, end < 0 ? text.length : end);
    return {
      family: (/font-family\s*:\s*([^;}]*)/iu.exec(block)?.[1] ?? "").replace(/["']/gu, "").trim(),
      style: (/font-style\s*:\s*([^;}]*)/iu.exec(block)?.[1] ?? "normal").trim(),
    };
  });
}

/** Whether a `font-family` or `font` value names its family only through a `--face-*` token (or is a CSS-wide keyword). */
function readsFaceToken(property: string, value: string): boolean {
  const v = value.replace(/\s*!important\s*$/u, "").trim();
  if (CSS_WIDE.test(v)) return true;
  // font-family is the token and nothing else (a family appended after it is a second declaration);
  // the font shorthand ends in the token, with no family list of its own.
  return property.toLowerCase() === "font-family" ? /^var\(\s*--face-[\w-]+\s*\)$/u.test(v) : /(?:^|\s)var\(\s*--face-[\w-]+\s*\)$/u.test(v) && !/[,"']/u.test(v);
}

/** Every font-source and declare-once violation in one build input. `owner` is true for the token owner. */
export function fontFindings(path: string, text: string, declared: ReadonlySet<string>): string[] {
  const findings: string[] = [];
  const kind = KINDS[extname(path).toLowerCase()];
  const owner = path === TOKENS;
  const judgeCss = (css: string, where: string): void => {
    for (const unit of cssUnits(css)) {
      if (unit.kind === "font-face" && !owner) findings.push(`${where}: @font-face outside ${TOKENS}`);
      if (unit.kind === "import" && isRemote(unit.value)) findings.push(`${where}: @import of the remote ${unit.value}`);
      if (unit.kind === "url" && isRemote(unit.value)) findings.push(`${where}: url(${unit.value}) is remote`);
      else if (unit.kind === "url" && FONT_FILE.test(unit.value) && !declared.has(unit.value)) findings.push(`${where}: url(${unit.value}) is a font file the owner does not declare`);
    }
    for (const d of fontDeclarations(css)) {
      if (d.property.startsWith("--face-")) {
        if (!owner) findings.push(`${where}: ${d.property} is defined outside ${TOKENS}`);
      } else if (!d.inFace && !readsFaceToken(d.property, d.value)) findings.push(`${where}: ${d.property}: ${d.value} names a family instead of a --face-* token`);
    }
    // One @font-face block per family and style; and each --face-* stack defined once.
    const count = (keys: string[]): Map<string, number> => keys.reduce((m, k) => m.set(k, (m.get(k) ?? 0) + 1), new Map<string, number>());
    for (const [key, n] of count(faceBlocks(css).map((f) => `${f.family}/${f.style}`))) if (n > 1) findings.push(`${where}: @font-face for ${key} is declared ${n} times`);
    for (const [key, n] of count(fontDeclarations(css).filter((d) => d.property.startsWith("--face-")).map((d) => d.property))) if (n > 1) findings.push(`${where}: ${key} is defined ${n} times`);
  };
  const judgeScript = (code: string, where: string): void => {
    const { strings, code: bare } = scriptStrings(code);
    if (/\bnew\s+FontFace\s*\(/u.test(bare)) findings.push(`${where}: new FontFace (a runtime font source)`);
    if (/\bdocument\s*\.\s*fonts\s*\.\s*add\s*\(/u.test(bare)) findings.push(`${where}: document.fonts.add (a runtime font source)`);
    if (/\bWebFont\s*\.\s*load\s*\(/u.test(bare)) findings.push(`${where}: WebFont.load (a font loader)`);
    if (/\.\s*fontFamily\s*=(?!=)/u.test(bare)) findings.push(`${where}: sets style.fontFamily (a family named outside the owner)`);
    // A canvas names its family in `ctx.font` (and a style in `style.font`): a family outside the owner either way.
    if (/\.\s*font\s*=(?!=)/u.test(bare)) findings.push(`${where}: sets .font (a canvas or style font names a family outside the owner)`);
    for (const str of strings) {
      if (/^(?:@fontsource(?:-variable)?\/|typeface-|webfontloader$|@ibm\/plex)/u.test(str)) findings.push(`${where}: imports the font package ${str}`);
      else if (isRemote(str) && (FONT_FILE.test(str) || STYLESHEET_FILE.test(str))) findings.push(`${where}: names the remote ${str}`);
      else if (/\burl\(\s*["']?(?:[a-z][a-z0-9+.-]*:)?\/\//iu.test(str)) findings.push(`${where}: a CSS url() to a remote source in ${str}`);
      else if (FONT_FILE.test(str) && !declared.has(str)) findings.push(`${where}: names the font file ${str}, which the owner does not declare`);
      else if (/(?:^|[;{\s])(?:font-family|font)\s*:/iu.test(str)) {
        for (const d of fontDeclarations(str)) if (!d.property.startsWith("--face-") && !readsFaceToken(d.property, d.value)) findings.push(`${where}: ${d.property}: ${d.value} in a string names a family instead of a --face-* token`);
      }
    }
  };
  const judgeMarkup = (markup: string, where: string): void => {
    for (const link of linkTags(markup)) {
      const href = link.href ?? "";
      const rel = (link.rel ?? "").toLowerCase();
      if (isRemote(href)) findings.push(`${where}: <link rel="${rel}"> to the remote ${href}`);
      else if (/\bpreload\b/u.test(rel) && (link.as ?? "").toLowerCase() === "font" && !declared.has(href)) findings.push(`${where}: preloads the font ${href}, which the owner does not declare`);
    }
    // A style attribute or directive is a stylesheet too.
    for (const m of markup.matchAll(/\sstyle\s*=\s*(?:"([^"]*)"|'([^']*)')/giu)) judgeCss(`x{${m[1] ?? m[2]}}`, `${where} (style attribute)`);
    for (const m of markup.matchAll(/\sstyle:(font-family|font)\s*=\s*(?:"([^"]*)"|'([^']*)'|\{([^}]*)\})/giu)) {
      const value = (m[2] ?? m[3] ?? m[4] ?? "").trim();
      if (!readsFaceToken(m[1]!, value.replace(/^["'`]|["'`]$/gu, ""))) findings.push(`${where}: style:${m[1]} names a family instead of a --face-* token`);
    }
  };
  if (kind === "css") judgeCss(text, path);
  else if (kind === "markup") {
    const { styles, scripts, scriptTags, markup } = splitMarkup(text);
    styles.forEach((css) => judgeCss(css, path));
    scripts.forEach((code) => judgeScript(code, path));
    // A remote script is code the guard cannot read: it could load a font from anywhere.
    for (const tag of scriptTags) if (isRemote(tagAttributes(tag).src ?? "")) findings.push(`${path}: <script src> from the remote ${tagAttributes(tag).src}`);
    judgeMarkup(markup, path);
  } else if (kind === "script") judgeScript(text, path);
  else if (kind === undefined) findings.push(`${path}: a build input of a kind this guard does not parse (${extname(path) || "no extension"})`);
  return findings;
}

// ── The population: what the build consumes ─────────────────────────────

/** The local references one build input makes, as written (scripts: imports, re-exports, dynamic imports, glob patterns; markup: script src and link href; stylesheets: @import). */
export function localReferences(path: string, text: string): { references: { spec: string; glob: boolean }[]; findings: string[] } {
  const references: { spec: string; glob: boolean }[] = [];
  const findings: string[] = [];
  const kind = KINDS[extname(path).toLowerCase()];
  // The analyzer reads a script by its extension; a page's or a component's script is TypeScript-or-JavaScript.
  const scriptName = /\.(?:[cm]?[jt]sx?)$/u.test(path) ? path : `${path}.ts`;
  const fromScript = (code: string): void => {
    const analysis = analyzeStaticSource(code, scriptName);
    if (analysis.unmodeledModuleAcquisition) findings.push(`${path}: a module acquisition the analyzer cannot model`);
    for (const a of analysis.moduleAcquisitions) {
      if (a.specifier === null) findings.push(`${path}: a ${a.kind} with a computed specifier the guard cannot follow`);
      else references.push({ spec: a.specifier, glob: false });
    }
    const tokens = tokenizeStaticSource(code, scriptName);
    tokens.forEach((t, i) => {
      if (t.value !== "glob" || tokens[i - 1]?.value !== "." || tokens[i - 2]?.value !== "meta" || tokens[i - 4]?.value !== "import" || tokens[i + 1]?.value !== "(") return;
      for (let j = i + 2; j < tokens.length && tokens[j]!.value !== ")" && tokens[j]!.value !== "{"; j += 1) {
        if (tokens[j]!.kind === "string") references.push({ spec: tokens[j]!.value, glob: true });
        else if (tokens[j]!.kind === "template") findings.push(`${path}: an import.meta.glob pattern the guard cannot read`);
      }
    });
  };
  if (kind === "script") fromScript(text);
  else if (kind === "markup") {
    const { styles, scripts, scriptTags, markup } = splitMarkup(text);
    scripts.forEach(fromScript);
    for (const css of styles) for (const u of cssUnits(css)) if (u.kind === "import" && !isRemote(u.value)) references.push({ spec: u.value, glob: false });
    for (const tag of scriptTags) {
      const src = tagAttributes(tag).src;
      if (src !== undefined && !isRemote(src)) references.push({ spec: src, glob: false });
    }
    for (const link of linkTags(markup)) if (link.href !== undefined && !isRemote(link.href) && !/\bpreload\b/u.test(link.rel ?? "")) references.push({ spec: link.href, glob: false });
  } else if (kind === "css") {
    for (const u of cssUnits(text)) if (u.kind === "import" && !isRemote(u.value)) references.push({ spec: u.value, glob: false });
  }
  return { references, findings };
}

const RESOLVE_SUFFIXES = ["", ".ts", ".js", ".svelte", ".mjs", ".json", "/index.ts", "/index.js"];

/** Every file the build consumes, as root-relative paths, and the findings met while finding them. */
export function buildInputs(config: { root?: string; publicDir?: string | false; optimizeDeps?: { entries?: string | string[] } }): { files: string[]; findings: string[] } {
  const root = resolve(config.root ?? ".");
  const publicDir = resolve(root, config.publicDir === undefined ? "public" : config.publicDir === false ? "" : config.publicDir);
  const entries = [config.optimizeDeps?.entries ?? []].flat().flatMap((pattern) => globSync(pattern, { cwd: root }).map((f) => resolve(root, f)));
  const findings: string[] = [];
  if (entries.length === 0) findings.push("the build declares no entry page");
  const seen = new Set<string>();
  const queue = [...entries];
  const isFile = (p: string): boolean => existsSync(p) && statSync(p).isFile();
  while (queue.length > 0) {
    const file = queue.shift()!;
    if (seen.has(file)) continue;
    seen.add(file);
    const refs = localReferences(relative(root, file), readFileSync(file, "utf8"));
    findings.push(...refs.findings);
    for (const { spec, glob } of refs.references) {
      const bare = spec.replace(/[?#].*$/u, "");
      if (glob) {
        const matched = globSync(bare, { cwd: dirname(file) }).map((f) => resolve(dirname(file), f));
        if (matched.length === 0) findings.push(`${relative(root, file)}: import.meta.glob("${spec}") matches nothing`);
        queue.push(...matched);
        continue;
      }
      if (bare.startsWith(".") || bare.startsWith("/")) {
        const bases = bare.startsWith("/") ? [join(root, bare), join(publicDir, bare)] : [resolve(dirname(file), bare)];
        const hit = bases.flatMap((b) => RESOLVE_SUFFIXES.map((x) => b + x)).find(isFile);
        if (hit === undefined) findings.push(`${relative(root, file)}: the reference ${spec} resolves to no file`);
        else queue.push(hit);
      } else if (STYLESHEET_FILE.test(bare) || KINDS[extname(bare).toLowerCase()] === "css") {
        // A package stylesheet the client imports is bundled: judge it.
        try {
          queue.push(createRequire(file).resolve(bare));
        } catch {
          findings.push(`${relative(root, file)}: the package stylesheet ${spec} does not resolve`);
        }
      }
    }
  }
  const publicFiles = existsSync(publicDir)
    ? execFileSync("git", ["ls-files", "-z", "--", relative(root, publicDir)], { cwd: root, encoding: "utf8" }).split("\0").filter((f) => f.length > 0).map((f) => resolve(root, f))
    : [];
  for (const f of publicFiles) seen.add(f);
  return { files: [...seen].map((f) => relative(root, f).split("\\").join("/")).sort(), findings };
}

type Lock = { schema: string; packages: { name: string; version: string; integrity: string }[]; files: { file: string; package: string; path: string; sha256: string }[] };

describe("fonts: one declaration, pinned files, no other source", () => {
  const owner = read(TOKENS);
  const declared = declaredSources(owner);

  test("the owner declares Plex Sans and Plex Mono, roman and italic, from /fonts/", () => {
    expect([...declared].sort()).toEqual([
      "/fonts/ibm-plex-mono-var-italic-latin1.woff2",
      "/fonts/ibm-plex-mono-var-roman-latin1.woff2",
      "/fonts/ibm-plex-sans-var-italic-latin1.woff2",
      "/fonts/ibm-plex-sans-var-roman-latin1.woff2",
    ]);
    expect(owner).toMatch(/--face-sans:\s*"IBM Plex Sans Variable"/u);
    expect(owner).toMatch(/--face-mono:\s*"IBM Plex Mono Variable"/u);
  });

  test("every vendored file is pinned to IBM's npm release and matches its digest; every declared source is pinned", () => {
    const lock = JSON.parse(read(LOCK)) as Lock;
    expect(lock.schema).toBe("bridlewise-font-lock/v1");
    for (const pkg of lock.packages) expect(pkg.integrity, `${pkg.name}@${pkg.version} carries its registry integrity`).toMatch(/^sha512-[A-Za-z0-9+/]+=*$/u);
    const vendored = readdirSync(FONT_DIR).filter((f) => FONT_FILE.test(f)).sort();
    expect(lock.files.map((f) => f.file).sort()).toEqual(vendored);
    for (const entry of lock.files) {
      const digest = createHash("sha256").update(readFileSync(`${FONT_DIR}/${entry.file}`)).digest("hex");
      expect(digest, `${entry.file} differs from its pin: run node scripts/vendor-fonts.ts --write`).toBe(entry.sha256);
      expect(lock.packages.some((p) => p.name === entry.package), `${entry.file}'s package is pinned`).toBe(true);
    }
    expect([...declared].map((s) => s.replace(/^\/fonts\//u, "")).sort()).toEqual(vendored);
    expect(existsSync(`${FONT_DIR}/OFL.txt`), "the OFL licence travels with the fonts").toBe(true);
  });

  test("everything the build consumes loads no font from elsewhere and declares no family twice", () => {
    const inputs = buildInputs(BUILD_CONFIG as Parameters<typeof buildInputs>[0]);
    expect(inputs.findings, "the walk reached every reference").toEqual([]);
    // The population is the build's own: the entry page, the client modules it reaches, the owner, the public files.
    expect(inputs.files).toEqual(expect.arrayContaining(["index.html", "src/main.ts", TOKENS, "src/cockpit/shell/Brand.svelte", "public/manifest.json", "public/fonts/fonts.lock.json"]));
    expect(inputs.files.length, "population is live").toBeGreaterThan(200);
    expect(inputs.files.filter((f) => f.startsWith("engine/large-codebases/")), "the corpus is not a build input").toEqual([]);
    expect(inputs.files.flatMap((f) => fontFindings(f, KINDS[extname(f).toLowerCase()] === "inert" ? "" : read(f), declared))).toEqual([]);
    // The owner's own declarations: one block per family and style, and each stack once.
    expect(faceBlocks(owner).map((f) => `${f.family}/${f.style}`).sort()).toEqual(["IBM Plex Mono Variable/italic", "IBM Plex Mono Variable/normal", "IBM Plex Sans Variable/italic", "IBM Plex Sans Variable/normal"]);
  });

  test("mutation: every kind of planted source is refused, on any host; near-misses pass", () => {
    const plants: [string, string][] = [
      ["src/cockpit/rooms/A.svelte", '<style>@font-face { font-family: "X"; src: url("/fonts/x.woff2"); }</style>'],
      ["src/app.css", '@import url("https://fonts.googleapis.com/css2?family=Inter");'],
      ["src/app.css", "@import 'https://cdn.example/fonts.css';"],
      ["src/app.scss", '@import "https://cdn.example/fonts.css";'],
      ["src/cockpit/tokens.css", '@font-face { font-family: "Y"; src: url("https://fonts.gstatic.com/y.woff2"); }'],
      ["src/cockpit/tokens.css", '@font-face { font-family: "Y"; src: url("https://cdn.example.org/y"); }'],
      ["src/b.css", ".x { background: url(/assets/Inter.woff2); }"],
      ["src/b.css", ".x { background: url(//cdn.example.org/anything); }"],
      ["index.html", '<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Roboto">'],
      ["index.html", '<link rel="stylesheet" href="https://cdn.example.org/brand.css">'],
      ["index.html", '<link rel="preconnect" href="https://cdn.example.org" crossorigin>'],
      ["index.html", '<script src="https://cdn.example.org/webfont.js"></script>'],
      ["index.html", '<link rel="preload" as="font" href="/fonts/extra.woff2" type="font/woff2" crossorigin>'],
      ["src/main.ts", 'const f = new FontFace("Z", "url(/z.woff2)"); document.fonts.add(f);'],
      ["src/main.ts", 'import "@fontsource/inter";'],
      ["src/c.svelte", '<script>WebFont.load({ google: { families: ["Lato"] } });</script>'],
      ["src/d.ts", 'export const font = "/static/brand.ttf";'],
      ["src/d.mjs", 'export const sheet = "https://cdn.example.org/type/brand.css";'],
      ["src/d.tsx", 'export const face = "https://cdn.example.org/type/brand.woff2";'],
      ["src/d.ts", 'el.style.cssText = "background: url(https://cdn.example.org/x)";'],
    ];
    for (const [path, text] of plants) expect(fontFindings(path, text, declared), `${path}: ${text}`).not.toEqual([]);
    // The @font-face rule by its own name: a face outside the owner is refused even when its file is a declared one.
    expect(fontFindings("src/cockpit/rooms/A.svelte", '<style>@font-face { font-family: "IBM Plex Sans Variable"; src: url("/fonts/ibm-plex-sans-var-roman-latin1.woff2"); }</style>', declared)).toEqual([`src/cockpit/rooms/A.svelte: @font-face outside ${TOKENS}`]);
    // A kind the guard cannot parse is refused, not skipped.
    expect(fontFindings("src/e.vue", "<template></template>", declared)).toEqual(["src/e.vue: a build input of a kind this guard does not parse (.vue)"]);
    // Upper-case and spaced tags are still cut out: a style in <STYLE > is judged, a link in a comment is not.
    expect(fontFindings("index.html", '<STYLE type="text/css">@import "https://cdn.example.org/x.css";</STYLE ><!-- <link rel="stylesheet" href="https://cdn.example.org/x"> -->', declared)).toHaveLength(1);
    // Near-misses: the owner's own faces; a comment naming a remote; a declared preload; a local link; an API URL string.
    expect(fontFindings(TOKENS, owner, declared)).toEqual([]);
    expect(fontFindings("src/a.css", "/* never https://fonts.googleapis.com */ .a { background: url(/icons/icon.svg); font-family: var(--face-sans); }", declared)).toEqual([]);
    expect(fontFindings("index.html", '<link rel="preload" as="font" href="/fonts/ibm-plex-sans-var-roman-latin1.woff2" crossorigin><link rel="manifest" href="/manifest.json">', declared)).toEqual([]);
    expect(fontFindings("src/e.ts", '// new FontFace("x") in a comment\nconst label = "Fonts are self-hosted"; const api = "https://api.example.org/v1/chat";', declared)).toEqual([]);
    expect(cssUnits('@font-face{src:url( "/fonts/a.woff2" ) format("woff2")} /* url(/x.woff2) */ .a{content:"url(/y.woff2)"}').map(({ kind, value }) => [kind, value])).toEqual([["font-face", ""], ["url", "/fonts/a.woff2"]]);
  });

  test("mutation: a family declared twice is refused wherever the second one is written", () => {
    // A second @font-face for the same family and style in the owner.
    const first = cssUnits(owner).find((u) => u.kind === "font-face")!.at;
    const face = owner.slice(first, owner.indexOf("}", first) + 1);
    expect(fontFindings(TOKENS, `${owner}\n${face}\n`, declared).join("\n")).toMatch(/@font-face for IBM Plex Sans Variable\/normal is declared 2 times/u);
    // A second --face-sans stack, in the owner or anywhere else.
    expect(fontFindings(TOKENS, `${owner}\n:root { --face-sans: "Inter", sans-serif; }\n`, declared).join("\n")).toMatch(/--face-sans is defined 2 times/u);
    expect(fontFindings("src/cockpit/rooms/A.svelte", "<style>.a { --face-sans: Inter; }</style>", declared)).toEqual([`src/cockpit/rooms/A.svelte: --face-sans is defined outside ${TOKENS}`]);
    // A family named directly, in a stylesheet, a style attribute, a style directive and a script.
    expect(fontFindings("src/b.css", '.a { font-family: "IBM Plex Sans Variable", sans-serif; }', declared)).toHaveLength(1);
    expect(fontFindings("src/b.css", ".a { font: 600 1rem/1.2 Inter; }", declared)).toHaveLength(1);
    expect(fontFindings("src/b.css", ".a { font-family: var(--face-sans), Georgia; }", declared), "a family appended after the token").toHaveLength(1);
    expect(fontFindings("src/b.css", ".a { font: 600 1rem var(--face-sans), Georgia; }", declared), "the shorthand with a family list").toHaveLength(1);
    expect(fontFindings("src/c.svelte", '<p style="font-family: Inter">x</p>', declared)).toHaveLength(1);
    expect(fontFindings("src/c.svelte", '<p style:font-family="Inter">x</p>', declared)).toHaveLength(1);
    expect(fontFindings("src/d.ts", 'node.style.fontFamily = "Inter";', declared)).toHaveLength(1);
    expect(fontFindings("src/d.ts", 'ctx.font = "12px Georgia";', declared), "a canvas font").toHaveLength(1);
    expect(fontFindings("src/d.ts", "node.style.font = `600 1rem ${family}`;", declared), "a style shorthand set from script").toHaveLength(1);
    expect(fontFindings("src/d.ts", "if (ctx.font === previous) redraw();", declared), "a comparison is not an assignment").toEqual([]);
    expect(fontFindings("src/d.ts", 'const css = ".x { font-family: Inter; }";', declared)).toHaveLength(1);
    // Near-misses: every reading of the token, a CSS-wide keyword, and a font shorthand ending in the token.
    expect(fontFindings("src/b.css", ".a { font-family: var(--face-mono); } .b { font: var(--f-ui-size) var(--face-sans); } .c { font-family: inherit; }", declared)).toEqual([]);
    expect(fontFindings("src/c.svelte", '<p style="font-family: var(--face-sans)">x</p>', declared)).toEqual([]);
  });

  test("the population walk follows what the build follows, and refuses what it cannot", () => {
    const refs = localReferences("src/x.ts", 'import a from "./a"; export * from "./b"; const c = import("./c"); const g = import.meta.glob("../rooms/*Room.svelte"); import type { T } from "./t";');
    expect(refs.references.map((r) => `${r.glob ? "glob:" : ""}${r.spec}`).sort()).toEqual(["./a", "./b", "./c", "glob:../rooms/*Room.svelte"]);
    expect(localReferences("src/x.ts", "const m = await import(name);").findings.join("\n")).toMatch(/computed specifier/u);
    expect(localReferences("index.html", '<script type="module" src="/src/main.ts"></script><link rel="manifest" href="/manifest.json"><link rel="stylesheet" href="https://cdn.example.org/x.css">').references.map((r) => r.spec)).toEqual(["/src/main.ts", "/manifest.json"]);
    expect(localReferences("src/a.css", '@import "./b.css"; @import url(./c.css);').references.map((r) => r.spec)).toEqual(["./b.css", "./c.css"]);
  });
});
