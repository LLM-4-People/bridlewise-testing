/**
 * ONE FONT DECLARATION, NO OTHER SOURCE — structurally.
 *
 * The cockpit's token owner (`src/cockpit/tokens.css`) declares the fonts:
 * its `@font-face` blocks name the self-hosted files, and its `--face-*`
 * tokens name the family stacks. Those are the ONLY font declarations, and
 * self-hosted files the ONLY font sources, in everything the build consumes.
 *
 * THE POPULATION IS THE BUILD'S OWN INPUTS, NOT A HAND LIST OF FOLDERS OR
 * EXTENSIONS. It starts from the pages the build configuration declares
 * (`vite.config.ts`'s `BUILD_CONFIG`: its root and `optimizeDeps.entries`)
 * and follows every reference the build follows — a page's `<script src>`
 * and `<link href>`, a module's imports, re-exports, dynamic imports and
 * `import.meta.glob` patterns (the engine's static-source analyzer and
 * tokenizer read them), a stylesheet's `@import` — plus every file of the
 * public directory, which the build copies as is. Every file reached is
 * judged by its kind; a kind the guard cannot parse, a reference it cannot
 * resolve and an acquisition it cannot model are refused, never skipped.
 * Package JavaScript is not walked (its fonts would arrive through a
 * stylesheet or a font package, both judged); a package stylesheet the
 * client imports is.
 *
 * The rules:
 *
 *   SOURCES  no remote font source at all, on any host: a stylesheet
 *            `@import`s or `url()`s nothing remote; markup `<link>`s nothing
 *            remote; a script loads no font at runtime (`new FontFace`,
 *            `document.fonts.add`, `WebFont.load`), imports no font package,
 *            and names no remote font file, stylesheet or `url()`. Every
 *            local font file named anywhere is one the owner declares.
 *   ONCE     `@font-face` only in the owner, one block per family and style;
 *            the `--face-*` stacks defined once, in the owner; every other
 *            `font-family` or `font` reads a `--face-*` token (or a CSS-wide
 *            keyword), so no family is named twice — in a stylesheet, a
 *            style attribute or directive, or a script string.
 *
 * The vendored files are pinned in `public/fonts/fonts.lock.json` (generated by
 * `scripts/vendor-fonts.ts` from IBM's npm releases, whose registry integrity
 * it records): every vendored file's digest must match its pin, and every
 * declared source must be a pinned file. The scanners are pure functions,
 * mutation-tested below with planted violations of every kind and
 * near-misses that must pass.
 */
